"""Промпт агенту на описание СТРУКТУРЫ баз данных (BYOA, Ф5).

Отдельный от docs_prompt: там агента просят РИСОВАТЬ (схемы логики) и добывать спеку,
здесь — ЧИТАТЬ миграции и ORM-модели и выдавать записи. Задачи разные, и смешивать их
в одном полотне значило бы получить и то, и другое вполсилы.

Только структура. Обращения к данным («кто читает orders.status») в этот пакет НЕ
входят: они живут пометками в тексте схем логики (пивот §9 plan-db-docs.md), и промпт
обязан сказать это прямо — иначе агент по привычке пришлёт раздел, который некуда деть.

Промпт ПАРАМЕТРИЗОВАН узлами-БД проекта (находка №1 полевого QA). Среза схемы, как в
docs_prompt, здесь не надо — нужен только адрес владельца записей; без списка слабая
модель его ВЫДУМЫВАЕТ («Zabbix Storage»), и пакет блокируется целиком.
"""

# Адрес для примера, когда подставить нечего (узлов-БД в проекте нет).
_FALLBACK_ADDR = "Платформа / Хранилище"


def _address_lines(db_paths: list[str]) -> tuple[str, str]:
    """Строка про узлы-БД проекта + адрес для примера формата.

    Один узел — в примере стоит ровно он: места для выдумки не остаётся. Ни одного —
    честно говорим, что адресовать пока некуда, вместо молчаливого промаха мимо базы.
    """
    if not db_paths:
        return (
            "В проекте ещё нет узла-БД — сначала создайте его; без адреса записи уедут "
            "к объекту, со страницы которого открыто окно.",
            _FALLBACK_ADDR,
        )
    if len(db_paths) == 1:
        return (
            f"Узел-БД в этом проекте один — «{db_paths[0]}»: пиши ровно этот адрес.",
            db_paths[0],
        )
    listed = ", ".join(f"«{p}»" for p in db_paths)
    return (
        f"Узлы-БД этого проекта: {listed}. Адрес бери ДОСЛОВНО из этого перечня — "
        "других баз в проекте нет.",
        db_paths[0],
    )


def build_data_prompt(db_paths: list[str]) -> str:
    """Собрать текст промпта. db_paths — полные пути узлов-БД проекта (shape=database)
    в терминах импорта: они и есть допустимые адреса владельца записей."""
    nodes_line, example_addr = _address_lines(db_paths)

    return f"""# ArchMap · описание структуры баз данных

Опиши СТРУКТУРУ баз данных этого репозитория — таблицы и колонки, как они заданы в
коде. Итог: файлы в каталоге `archmap-docs/`, которые человек загрузит в ArchMap.

## Где это делать (важно)

Запускай эту задачу в репозитории ВЛАДЕЛЬЦА базы — там, где лежат её миграции и
ORM-модели. Репозиторий сервиса, который в базу только ходит, структуры не знает:
оттуда получится пересказ запросов, а не схема.

Обращения к данным описываются НЕ здесь, а пометками «читает:/пишет:» в схемах логики
сервисов — раздела для них в этом формате нет.

## Что делать

1. Найди описание схемы БД: миграции (alembic/, migrations/, *.sql), ORM-модели
   (SQLAlchemy/Django/GORM/Prisma/Entity Framework). НЕ подключайся к живой базе.
2. Выпиши таблицы и колонки — так, как они в коде: имя, тип как в DDL, обязательность,
   первичный ключ, внешние ключи.
3. Сложи результат в файлы `archmap-docs/<что-угодно>.yaml` по формату ниже.

## Куда адресовать

Адрес узла-владельца пиши КОММЕНТАРИЕМ первой строкой файла: «# archmap-node: <адрес>»,
именно с решёткой. Без неё строка станет обычным YAML-ключом, адреса ArchMap не увидит.
В этой строке — только адрес: хвост-пояснение после него станет частью адреса.
{nodes_line}

## Формат файла

```yaml
# archmap-node: {example_addr}
tables:
  - name: orders
    schema: public            # раздел базы; можно опустить
    description: заказы покупателей
    columns:
      - name: id
        type: uuid
        pk: true
        required: true
      - name: status
        type: varchar(16)
        required: true
        description: new|paid|shipped   # РАСШИФРОВЫВАЙ такие значения
      - name: account_id
        type: uuid
        references: accounts.id         # таблица.колонка той же базы
```

`schema` — раздел базы в терминах твоего движка: schema в PostgreSQL, database в
MySQL/Mongo/ClickHouse, keyspace в Cassandra. Один раздел — оставь поле пустым.

## Правила

- `description` у колонок со значениями-состояниями ОБЯЗАТЕЛЕН: «status: new|paid|
  shipped» — это самый частый вопрос сопровождения.
- Ничего не удаляй и не «подчищай»: чего в файле нет, то в ArchMap останется как было.
- Индексы, партиционирование, тюнинг и историю миграций НЕ описывай — это другая
  задача, а объём документации они удваивают.
- Не выдумывай. Если таблица есть, а её назначение из кода не следует — оставь
  `description` пустым.
"""
