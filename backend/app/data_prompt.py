"""Промпт агенту на описание структуры БД и обращений к данным (BYOA, Ф5).

Отдельный от docs_prompt: там агента просят РИСОВАТЬ (схемы логики) и добывать спеку,
здесь — ЧИТАТЬ миграции и ORM-модели и выдавать записи. Задачи разные, и смешивать их
в одном полотне значило бы получить и то, и другое вполсилы.

Главное, что промпт обязан объяснить: обращения — не украшение, а цель. Инженеру
сопровождения нужен не перечень таблиц, а ответ «откуда взялось это значение».
"""

PROMPT = """# ArchMap · описание данных

Опиши БАЗЫ ДАННЫХ этого репозитория и ОБРАЩЕНИЯ к ним — что каждая операция сервиса
читает и что пишет. Итог: файлы в каталоге `archmap-docs/`, которые человек загрузит
в ArchMap.

## Зачем это (не пропускай — от этого зависит, что важно)

Читать будет инженер сопровождения с вопросом «откуда в этом сценарии взялось вот это
значение». Перечень таблиц отвечает лишь «где значение может лежать»; ответ даёт
связка «операция → таблица.колонка, читает или пишет». Поэтому раздел `access` важнее
раздела `tables`, а не наоборот.

## Что делать

1. Найди описание схемы БД: миграции (alembic/, migrations/, *.sql), ORM-модели
   (SQLAlchemy/Django/GORM/Prisma/Entity Framework). НЕ подключайся к живой базе.
2. Выпиши таблицы и колонки — так, как они в коде: имя, тип как в DDL, обязательность,
   первичный ключ, внешние ключи.
3. Пройди по операциям сервиса (те же точки входа, что и для схем логики) и выпиши,
   к каким таблицам и колонкам каждая обращается. Разделяй чтение и запись.
4. Сложи результат в файлы `archmap-docs/<что-угодно>.yaml` по формату ниже.

## Формат файла

```yaml
# archmap-node: Платформа / Хранилище      # чья это база; можно просто «Хранилище»
tables:
  - name: orders
    schema: public            # контур; можно опустить
    description: заказы покупателей
    columns:
      - name: id
        type: uuid
        pk: true
        required: true
      - name: status
        type: varchar(16)
        required: true
        description: new|paid|shipped   # РАСШИФРОВЫВАЙ такие значения
      - name: account_id
        type: uuid
        references: accounts.id         # таблица.колонка той же базы

access:
  - node: Платформа / Биллинг   # ЧЕЙ код обращается (сервис, не база)
    doc: POST /pay              # имя схемы логики этой операции — как в ArchMap
    table: orders               # можно «Хранилище / orders» при одноимённых
    column: status              # можно опустить: обращение к таблице целиком
    mode: write                 # read | write
```

## Правила

- `description` у колонок со значениями-состояниями ОБЯЗАТЕЛЕН: «status: new|paid|
  shipped» — это самый частый вопрос сопровождения.
- Колонка в `access` необязательна: если запрос берёт строку целиком (`SELECT *`),
  просто не указывай `column`. Не выдумывай точность, которой нет в коде.
- `mode: write` — любое изменение состояния (insert/update/delete); отдельного
  «delete» в модели нет.
- `doc` должен СОВПАДАТЬ с именем схемы логики в ArchMap (обычно «METHOD /путь»).
  Если схемы логики для операции ещё нет — сначала опиши логику, потом обращения.
- Ничего не удаляй и не «подчищай»: чего в файле нет, то в ArchMap останется как было.
- Индексы, партиционирование, тюнинг и историю миграций НЕ описывай — это другая
  задача, а объём документации они удваивают.
- Не выдумывай. Если таблица есть, а её назначение из кода не следует — оставь
  `description` пустым.
"""


def build_data_prompt() -> str:
    return PROMPT
