    """Текст промпта по варианту кнопки — общий переключатель ручек промптов.

    ⚠ builder возвращает переданный строительный промпт БАЙТ-В-БАЙТ: на дефолте
    сидят MCP-тулзы и нынешний фронт, и любая правка здесь тихо сменила бы им контракт.

    recon_builder — генератор промпта разведчика по пути результата. Нужен только
    оркестраторному варианту разведки: её петля гоняет ДВА прогона в разные файлы, и
    одним готовым текстом она не выражается.
    """
    if variant == "builder":
        return builder_prompt
    skeptic = build_skeptic_prompt(
        flow, system_name=system_name, orchestrated=variant == "orchestrated"
    )
    if variant == "skeptic":
        return skeptic
    if flow == "recon":
        if recon_builder is None:
            raise ValueError("Оркестраторной разведке нужен recon_builder — генератор по пути")
        return build_recon_orchestrated_prompt(recon_builder, skeptic)
    return build_orchestrated_prompt(builder_prompt, skeptic, flow)
