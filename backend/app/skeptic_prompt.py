def _import_subject(system_name: str | None) -> str:
    """Подлежащее импорта: имя системы вставляется так же, как в строительном промпте
    (лишние пробелы схлопываются) — аудитор ищет в модели ровно тот корень."""
    name = " ".join(system_name.split()) if system_name else ""
    if not name:
        return "архитектурная модель системы"
    return f"архитектурная модель системы «{name}»"


def build_skeptic_prompt(
    flow: Flow,
    *,
    system_name: str | None = None,
    orchestrated: bool = False,
) -> str:
    """Промпт агенту-АУДИТОРУ пакета потока flow.

    orchestrated=False — standalone: пакет собран отдельным прогоном, отчёт кладётся
    в корень репозитория и дублируется в ответ вместе с инструкцией передачи
    строителю. orchestrated=True — блок Б оркестраторной обёртки: служебные файлы
    петли лежат в archmap-orch/, отчёт нумерованный (петля делает несколько кругов).
    ⚠ Модель импорта в ОБОИХ режимах — один и тот же файл в корне (IMPORT_RESULT).

    Меняются между режимами ТОЛЬКО адресные части (где пакет, куда отчёт): роль,
    чек-лист, порог и формат общие — иначе два режима разъедутся по качеству.
    """
    if flow == "import":
        subject = _import_subject(system_name)
        where = (
            f"Проверяемое — модель в файле {IMPORT_RESULT}."
            if orchestrated
            else f"Проверяемое — модель в файле {IMPORT_RESULT} "
            "(если пользователь сохранил её в другом файле — возьми его)."
        )
    else:
        subject = _SUBJECTS[flow]
        where = _PACKAGE_WHERE[flow]

    if orchestrated:
        destination = (
            "Сохрани отчёт в файл `archmap-orch/skeptic-report-<N>.md`, где N — следующий "
            "свободный номер (1, 2, …): нет ни одного такого файла — пиши "
            "`skeptic-report-1.md`, иначе бери номер на единицу больше наибольшего. "
            "Уже существующие отчёты НЕ перезаписывай и не удаляй."
        )
        handoff = ""
    else:
        destination = (
            "Сохрани отчёт в файл `archmap-skeptic-report.md` в корне репозитория И "
            "продублируй его текст в ответ целиком."
        )
        handoff = f"\n{_HANDOFF}\n"

    return f"""# ArchMap · аудит документации (скептик)

Ты — ИИ-агент-АУДИТОР с доступом к файлам репозитория: умеешь искать по дереву, читать
файлы и искать текст по всему репозиторию.

Перед тобой {subject}. Она построена ДРУГИМ агентом по этому репозиторию. Считай её
НЕДОВЕРЕННОЙ: каждое утверждение — гипотеза, пока ты не подтвердил его кодом или
конфигом ЭТОГО репозитория.

{where}

## Что проверить (по списку, ничего не пропуская)

{_CHECKLISTS[flow]}

## Правила

- НИЧЕГО не исправляй: ни файлы пакета, ни другие файлы репозитория. Твой выход —
  только отчёт. Чинит другой агент.
- Каждый вердикт — С ДОКАЗАТЕЛЬСТВОМ: «путь/к/файлу:строка» либо «поиск по репозиторию
  не находит „X“». Без доказательства вердикта нет.
- Не советуй, как чинить, и не предлагай замену: твоё дело — назвать расхождение и
  доказательство.
- Подтверждённое в отчёт НЕ включай — только расхождения. Отчёт не отчитывается о
  проделанной работе, он перечисляет сомнения.
- Не выдумывай сомнений ради объёма. Расхождений нет — так и скажи.

## Порог уверенности

{THRESHOLD_V1}

## Формат отчёта

Одна строка на ОДНО сомнение, без вступления и без итогов. Формы строк:
{_REPORT_FORMS[flow]}
Пропуск — код использует то, чего в проверяемом НЕТ, — тоже сомнение, своей формой:
{_MISSING_FORMS[flow]}

Сомнений нет — весь отчёт состоит из единственной строки: {ALL_CONFIRMED}

{destination}
{handoff}"""


