def _report_section(flow: str) -> str:
    """Раздел «Формат отчёта»: формы строк и МЕСТО формы пропуска.

    ⚠ У четырёх потоков пропуск — довесок к проверке утверждений, у РАЗВЕДКИ он
    главный режим, а не приписка в хвосте: замер дал 17 верных пропусков и НОЛЬ
    ложных, причём системный пропуск (непрочитанный источник целиком) ловится почти
    нацело — 11/11. Спрятать эту форму в конец значило бы отменить главный выигрыш
    аудита разведки. Остальные потоки текст получают байт-в-байт прежний.
    """
    if flow == "recon":
        return (
            "ГЛАВНАЯ форма — ПРОПУСК: в коде есть точка входа, которой в перечне НЕТ. "
            "Ради неё этот аудит и затеян, с неё и начинай:\n"
            f"{_MISSING_FORMS[flow]}\n"
            f"Остальные формы — для строк, которые в перечне ЕСТЬ:\n{_REPORT_FORMS[flow]}"
        )
    return (
        f"Формы строк:\n{_REPORT_FORMS[flow]}\n"
        "Пропуск — код использует то, чего в проверяемом НЕТ, — тоже сомнение, своей "
        f"формой:\n{_MISSING_FORMS[flow]}"
    )

