"""Промпт агенту на описание КАНАЛОВ брокера (BYOA, Ф4 plan-broker-docs.md).

Близнец data_prompt по устройству (структура записями, адрес комментарием, промпт
параметризован узлами проекта), но с ключевым отличием, ради которого он отдельный
файл, а не флаг соседа: у брокера НЕТ репозитория-владельца. У базы структура лежит
в миграциях одного репозитория, и промпт может честно сказать «запускай у владельца»;
топики же объявлены там, где их публикуют и потребляют, — в коде каждого участника и
в инфра-конфигах. Поэтому здесь противоположная инструкция: прогоняй В КАЖДОМ
репозитории, который ходит в брокер, и описывай только то, что видит ЭТОТ код.

Отсюда же вытекает политика дозаливки (channels_import): пакеты разных репозиториев
доливаются друг к другу, а расхождение меты (два репо назвали разный retention) —
предупреждение, а не перезапись. Промпт обязан не поощрять выдумывание меты: пустое
поле здесь — законный и обычный ответ, а «правдоподобное» значение из головы дороже
пропуска, потому что по нему принимают решения о переигрывании и идемпотентности.

Обращения («кто публикует orders.created») в этот пакет НЕ входят: они живут пометками
«публикует:/потребляет:» в тексте схем логики (пивот §1) — промпт говорит это прямо,
иначе агент по привычке пришлёт раздел, который некуда деть.
"""

# Адрес для примера, когда подставить нечего (узлов-брокеров в проекте нет).
_FALLBACK_ADDR = "Платформа / Шина событий"


def _address_lines(broker_paths: list[str]) -> tuple[str, str]:
    """Строка про узлы-брокеры проекта + адрес для примера формата.

    Один узел — в примере стоит ровно он: места для выдумки не остаётся. Ни одного —
    честно говорим, что адресовать пока некуда (урок Н8: слепой адрес блокирует пакет
    целиком, и раунд переписки уходит на угадывание).
    """
    if not broker_paths:
        return (
            "В проекте ещё нет узла-брокера — сначала создайте его; без адреса каналы "
            "уедут к объекту, со страницы которого открыто окно.",
            _FALLBACK_ADDR,
        )
    if len(broker_paths) == 1:
        return (
            f"Узел-брокер в этом проекте один — «{broker_paths[0]}»: пиши ровно этот адрес.",
            broker_paths[0],
        )
    listed = ", ".join(f"«{p}»" for p in broker_paths)
    return (
        f"Узлы-брокеры этого проекта: {listed}. Адрес бери ДОСЛОВНО из этого перечня — "
        "других брокеров в проекте нет. Один прогон описывает каналы ОДНОГО брокера; "
        "ходит репозиторий в два — сделай два файла, у каждого свой адрес.",
        broker_paths[0],
    )


def build_channels_prompt(broker_paths: list[str]) -> str:
    """Собрать текст промпта. broker_paths — полные пути узлов-брокеров проекта
    (shape=broker) в терминах импорта: они и есть допустимые адреса владельца."""
    nodes_line, example_addr = _address_lines(broker_paths)

    return f"""# ArchMap · описание каналов брокера

Опиши КАНАЛЫ брокера — топики, очереди, exchange'и, — которые видно в коде ЭТОГО
репозитория, и поля их сообщений. Итог: файлы в каталоге `archmap-docs/`, которые
человек загрузит в ArchMap.

## Где это делать (важно)

У брокера нет «репозитория-владельца»: топик объявлен там, где его публикуют и
потребляют. Поэтому запускай эту задачу в КАЖДОМ репозитории, который в брокер ходит,
и описывай ТОЛЬКО те каналы, которые видит код этого репозитория. Пакеты разных
репозиториев доливаются друг к другу — ничего не потеряется и не задвоится.

Кто публикует и кто потребляет — описывается НЕ здесь, а пометками
«публикует:/потребляет:» в схемах логики сервисов: раздела для них в этом формате нет.

## Что делать

1. Найди объявления каналов: константы и конфиги с именами топиков/очередей, вызовы
   publish/produce/send и subscribe/consume, аннотации слушателей, схемы событий
   (schema registry, *.avsc, protobuf, JSON Schema), инфра-конфиги (terraform,
   docker-compose, helm) с созданием топиков. НЕ подключайся к живому брокеру.
2. Выпиши поля сообщения — из СЕРИАЛИЗАЦИИ: класс/структура события, схема реестра,
   тело publish. Тип пиши как в схеме («string», «uuid», «int64», «object»).
3. Сложи результат в файлы `archmap-docs/<что-угодно>.yaml` по формату ниже.

## Куда адресовать

Адрес узла-брокера пиши КОММЕНТАРИЕМ первой строкой файла: «# archmap-node: <адрес>»,
именно с решёткой. Без неё строка станет обычным YAML-ключом, адреса ArchMap не увидит.
В этой строке — только адрес: хвост-пояснение после него станет частью адреса.
{nodes_line}

## Формат файла

```yaml
# archmap-node: {example_addr}
channels:
  - name: orders.created
    group: ""                 # уровень изоляции брокера; можно опустить
    kind: topic               # topic | queue | exchange | stream | subject
    partition_key: order_id   # по нему определяется порядок событий
    delivery: at-least-once   # at-least-once | at-most-once | exactly-once
    retention: 7d             # «7d», «до ack», «compacted»
    description: заказ создан
    fields:
      - name: order_id
        type: uuid
        required: true
      - name: status
        type: string
        required: true
        description: new|paid|shipped   # РАСШИФРОВЫВАЙ такие значения
      - name: total
        type: int64
```

`group` — уровень изоляции в терминах твоего движка: vhost в RabbitMQ, namespace или
tenant в Pulsar, account в NATS. У Kafka такого уровня нет — оставь поле пустым.

## Правила

- Имена каналов бери ДОСЛОВНО из кода и конфигов: «orders.created», если константа
  называется так, а не «Заказ создан». Точки, дефисы и версии в имени — норма, их не
  трогай: по этому имени ArchMap сшивает канал с пометками в схемах логики.
- НЕ ВЫДУМЫВАЙ мету. `partition_key`, `delivery`, `retention` заполняй только тогда,
  когда они заданы в коде или инфра-конфиге (ключ в вызове publish, настройки
  консьюмера, terraform-ресурс топика). Не видно — оставь пустым: это законный и
  обычный ответ, а придуманная гарантия доставки хуже пустой, потому что по ней
  решают, обязана ли обработка быть идемпотентной.
- `description` у полей со значениями-состояниями ОБЯЗАТЕЛЕН: «status: new|paid|
  shipped», «event_type: created|cancelled» — это самый частый вопрос сопровождения.
- ЛЮБОЕ значение, внутри которого есть двоеточие с пробелом («статус: детали»),
  бери в двойные кавычки — самая частая причина битого YAML.
- Ничего не удаляй и не «подчищай»: чего в файле нет, то в ArchMap останется как было.
- Внутренние очереди в памяти, HTTP-вызовы и файлы каналами НЕ считай — только то,
  что реально проходит через брокер.
"""
