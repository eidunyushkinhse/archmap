"""Промпт агенту на РАЗВЕДКУ точек входа сервиса (Ф0 docs/plan-recon.md).

Шестой промпт проекта и единственный, который не производит документацию: агент
обходит репозиторий и возвращает ПЕРЕЧЕНЬ операций и фоновых процессов — оглавление,
по которому документирование пойдёт адресно, по строке за проход. Причина появления
полевая: Zulip получил 13 схем на 201 точку входа (покрытие 6.5%), и мешал не потолок
схем, а безадресность задания «опиши логику сервиса».

⚠ Текст перенесён из черновика, показавшего в замере 187/187 операций ядра и 14/14
очередей (docs/qa-recon-completeness.md). Это не эскиз, а ЗАМЕРЕННЫЙ артефакт:
процедура обхода, правила поиска и раздел «Честность» переписыванию «как лучше» НЕ
подлежат — редактура отменяет замер. Менять только новым замером.

⚠ КОНКРЕТНОГО пути в правилах нет и быть не должно. Полевой прогон
(docs/qa-recon-field.md) поймал класс, где иллюстрация утекла не в форму ответа, а в
его СОДЕРЖАНИЕ: у правила про сгенерированные циклом маршруты стоял пример с
выдуманным префиксом вебхуков — модель взяла из репозитория настоящий справочник
интеграций, приклеила к его именам префикс ИЗ ПРОМПТА и выдала 96 несуществующих
строк, 29% перечня. Пример сильнее правила: путь-шаблон агент обязан брать из кода,
поэтому правило называет ФОРМУ («с параметром на месте имени»), а не образец пути.

Формат ответа — YAML с корнем «# archmap-recon»: приёмник не должен спутать перечень
со спекой (у спеки есть openapi:/paths:). Имя класса-обработчика в перечень НЕ
пускаем: полнота списка ОЧЕРЕДЕЙ стабильна (14/14 в обоих прогонах), а имена классов
скачут 4/14 ↔ 14/14 — слабая модель синтезирует их по конвенции из имени очереди
(«embed_links» → «EmbedLinksWorker» вместо реального FetchLinksEmbedData).

Ни среза схемы, ни ранее разведанного перечня промпт НЕ несёт (решение пользователя,
§3 плана): разведка всегда идёт ОТ КОДА, иначе второй заход унаследует пропуски
первого. Единственный параметр — адрес узла-адресата.
"""

import yaml

# Куда разведчик кладёт перечень по умолчанию. ⚠ КОРЕНЬ репозитория, не archmap-docs/
# и не archmap-orch/: обе папки сносятся соседними BYOA-потоками и оркестратором на
# шаге 1 (см. комментарий к IMPORT_RESULT в skeptic_prompt.py) — перечень там не жилец.
RECON_FILE = "archmap-recon.yaml"


def _node_line(node_path: str) -> str:
    """Строка `node:` ОБРАЗЦА — yaml-дампом, а не подстановкой в f-строку.

    ⚠ Имена узлов в ArchMap свободные, и подстановка как есть делает пример НЕВАЛИДНЫМ
    YAML: «Zulip: сервер / backend» роняет разбор («mapping values are not allowed
    here»), «Zulip #1» обрезается комментарием до «Zulip», так же ломают ведущие
    `-`/`[`/`{`/`*`/`&`/`!`/`%`/`@`, хвостовые пробелы и кавычки. А пример сильнее
    правила: агент скопирует поломку в свой файл, и приёмник перечень не разберёт.

    Кавычки ставит библиотека — ровно там, где нужны, и канонично; самодельная
    эвристика этот класс не закрывает. Обычный адрес («Zulip / backend») остаётся БЕЗ
    кавычек: типичный случай образца не меняется. width — чтобы длинный адрес не
    переносился дампером на две строки.
    """
    return yaml.safe_dump(
        {"node": node_path}, allow_unicode=True, default_flow_style=False, width=10**9
    ).rstrip("\n")


def build_recon_prompt(node_path: str, *, result_path: str = RECON_FILE) -> str:
    """Собрать текст промпта разведки.

    node_path — полный путь узла-адресата в терминах импорта («Проект / Контейнер /
    Сервис»). Разведка без адреса бессмысленна, поэтому параметр обязателен.
    result_path — куда сохранить перечень (путь от корня репозитория). Параметр, а не
    константа, потому что оркестраторная петля гоняет ДВА независимых прогона в разные
    файлы и объединяет их (см. build_recon_orchestrated_prompt).
    """
    return f"""# Разведка сервиса: перечень точек входа

Ты работаешь в корне репозитория одного сервиса. Твоя задача — РАЗВЕДКА, нулевой шаг \
документирования: составить ПОЛНЫЙ ПЕРЕЧЕНЬ точек входа сервиса. Ничего не описывать, \
не рисовать схем, не объяснять, как это работает. Только перечень.

Перечень нужен как оглавление для последующей работы: по каждой строке потом будет \
отдельный проход. Пропущенная строка не даст о себе знать никак — её просто не \
задокументируют. Поэтому ПОЛНОТА здесь важнее краткости.

Собери два класса точек входа:
- **ОПЕРАЦИИ** — входящие вызовы к сервису: HTTP/REST-эндпоинты, gRPC-методы, \
GraphQL-операции. Формат строки — «METHOD /путь».
- **ВОРКЕРЫ** — фоновые процессы, которые сервис запускает сам: консьюмеры очередей, \
обработчики задач, кроны, демоны, периодические джобы. Формат строки — имя очереди, \
задачи, джоба или крона.

## Порядок обследования (иди по шагам, лишнего не читай)
1. Точки входа процессов: main.*, app.*, cmd/*, manage.py, wsgi/asgi-модули — какие \
процессы вообще существуют (HTTP-сервер, воркер, крон).
2. Объявления маршрутов. Ищи ФАЙЛ, где маршруты СОБРАНЫ В СПИСОК, — он даёт полный \
перечень разом: файлы вида urls/routes/router, регистрации роутеров и blueprint'ов, \
аннотации контроллеров, .proto (gRPC), schema.graphql. Такой файл — главный источник; \
найдя его, разбери ЕГО ЦЕЛИКОМ, от первой строки до последней.
3. Объявления воркеров. Ищи маркер, которым воркер помечается в ЭТОМ проекте: \
декоратор регистрации задачи или очереди, класс-наследник базового воркера, запись в \
реестре очередей, конфиг celery/sidekiq/systemd/supervisor, файлы cron.d и crontab, \
манифесты k8s CronJob.
4. Конфиги запуска: docker-compose*.yml, Procfile, supervisor/*.conf, systemd-юниты, \
k8s-манифесты, puppet/ansible — из них видны процессы, которых нет в коде явным \
списком (демоны, периодические команды).
5. Только после шагов 1–4 — точечные заглядывания в код, если чего-то не хватило.

ЗАПРЕЩЕНО: читать lock-файлы, node_modules/, vendor/, dist/, тесты, миграции, \
локализацию. Весь код читать НЕ нужно.

## Как искать, чтобы не пропустить
- Работай ПОИСКОМ ПО КОДУ (grep/rg), а не чтением подряд: перечень точек входа почти \
всегда лежит на одном-двух маркерах. Определи, какой маркер у этого проекта, выведи \
ВСЕ его вхождения и иди по ним, а не по памяти.
- ПОСЧИТАЙ вхождения маркера ДО того, как выписывать строки (`rg -c`), и сверь с \
длиной своего перечня в конце. Расхождение — значит, ты что-то потерял: вернись и \
добери.
- Один маршрут часто объявляет НЕСКОЛЬКО МЕТОДОВ сразу (`methods=["GET","POST"]`, \
`route(...).get(...).post(...)`, несколько методов-аргументов в одном объявлении). \
Каждый метод — ОТДЕЛЬНАЯ строка перечня.
- Маршруты бывают объявлены не только в главном файле: подключённые роутеры \
(`include(...)`, `include_router(...)`, `router.use(...)`), маршруты других приложений \
и модулей, маршруты, добавляемые в список НИЖЕ по файлу (`urls += [...]`, \
`.extend(...)`). Пройди и их.
- Маршруты бывают СГЕНЕРИРОВАНЫ циклом из справочника (`for x in SOMETHING: ...`). \
Такую группу выпиши ОДНОЙ строкой `operations`: путь-шаблон ДОСЛОВНО как в коде, с \
параметром на месте подставляемого имени; сколько их и из какого справочника — \
отдельной строкой в `sources`. Имена из справочника в отдельные строки НЕ \
разворачивай и префикс пути не додумывай: и путь, и префикс монтирования бери из \
кода, а не по образцу.
- Не останавливайся на «основных» — перечень должен быть полным, а не показательным. \
Если файл маршрутов длинный, это нормально: выписывай всё.

## Формат ответа (строго; любой другой текст сломает разбор)
Сначала запиши перечень в файл `{result_path}` (путь от корня репозитория), потом \
выведи его же в ответ. Файл — ровно такой:

```yaml
# archmap-recon
{_node_line(node_path)}
operations:
  - GET /messages
  - POST /messages
  - PATCH /messages/{{message_id}}
workers:
  - email_senders
  - missedmessage_emails
sources:
  - "операции: zerver/lib/rest.py (187 вхождений rest_path)"
  - "воркеры: zerver/worker/*.py (17 вхождений @assign_queue)"
doubts:
  - "GET /internal/metrics — похоже на служебный эндпоинт, не уверен"
```

Правила формата:
- Первая строка — ровно «# archmap-recon», именно с решёткой: по ней ArchMap узнаёт \
перечень и не путает его со спекой. Без решётки строка станет обычным YAML-ключом.
- `node` — адрес объекта, которому принадлежит перечень. Пиши его ДОСЛОВНО: \
«{node_path}». В этой строке — только адрес: хвост-пояснение после него станет частью \
адреса.
- `operations` — по строке на пару «метод + путь». Метод заглавными. Путь — ДОСЛОВНО \
как в коде, с ведущим слэшем; параметры пути оставляй как в исходнике \
(`<int:user_id>`, `{{userId}}`, `:id` — не переписывай в свою нотацию). Общий префикс \
монтирования не дописывай, если его нет в самой строке объявления. Если группа \
маршрутов подключается под общим префиксом, найди этот префикс в коде дословно \
(место подключения: `include(...)`, монтирование роутера, URLconf верхнего уровня) — \
префикс по догадке делает весь блок строк ложным.
- `workers` — по строке на воркер: ИМЯ ОЧЕРЕДИ, задачи, джоба или крона — то, чем \
воркер адресуется. Имя класса или функции-обработчика в этот раздел НЕ пиши: по имени \
очереди оно слишком легко достраивается по конвенции и выходит выдумкой. Хочешь \
назвать обработчика — его место в `sources`.
- `sources` — по строке на класс: где взял и сколько вхождений маркера насчитал. Это \
твоя же сверка: число вхождений должно объяснять длину перечня. Раздел обязателен.
- `doubts` — то, что похоже на точку входа, но ты не уверен. Лучше строка в \
«сомнениях», чем молчание. Раздел обязателен; сомнений нет — оставь `doubts: []`.
- Пример выше — из ЧУЖОГО репозитория (своя в нём только строка `node`). Это образец \
ФОРМАТА, а не данные: ни одна его строка, имя файла или маркер не должны попасть в \
твой ответ, если ты не увидел их в этом репозитории своими глазами.

## Честность
- Каждая строка перечня обязана иметь основание в файлах репозитория. Ничего не \
выдумывай и не добавляй «для полноты» и «по аналогии»: типовой эндпоинт, которого нет \
в коде (`GET /health`, `POST /login`), — ошибка, а не находка.
- Не переписывай пути «как правильнее»: перечень будут сверять с кодом дословно.
- Не сокращай перечень многоточием, «и т.д.», «остальные аналогично». Перечень либо \
полный, либо бесполезный.
- Не пиши ничего, кроме указанных разделов: ни вступления, ни выводов, ни описания \
архитектуры.
"""
