_PRODUCT = "shop-backend"
_NEIGHBOUR = "delivery"


def _drop_repo(node: dict) -> None:
    """Снять repo/path с узла и его потомков.

    Под федерацией адрес git-remote носит КОНТЕЙНЕР-ПРОДУКТ — он и есть этот
    репозиторий. Иначе пример нарушил бы собственный чек-лист (пункт 12: repo у
    нескольких узлов требует path у каждого) и показал бы два разных repo в
    документе, собранном по ОДНОМУ репозиторию."""
    source = node.get("source")
    if source is not None:
        source.pop("repo", None)
        source.pop("path", None)
        if not source:
            node.pop("source")
    for child in node.get("children", []):
        _drop_repo(child)


def _federated(doc: dict) -> dict:
    """Тот же пример, уложенный по правилам раздела «Проект объединяет НЕСКОЛЬКО
    продуктов»: всё содержимое репозитория уезжает под ОДИН контейнер-продукт,
    рядом с ним встаёт заглушка соседнего продукта (имя + host, без children,
    description и external), и одна связь уходит в соседа — образец межпродуктовой
    связи.

    ⚠ Трансформация ПРОГРАММНАЯ поверх _EXAMPLE_DOC. Второй захардкоженный пример
    молча протух бы при правке первого — а полевая матрица (находка 1
    docs/qa-federation-matrix.md) показала, что для слабой модели пример перевешивает
    правило: расхождение примера с текстом стоит дороже всего."""
    # Корень-система — единственный узел с детьми (актор и внешний SaaS их не имеют).
    root = next(n for n in doc["nodes"] if n.get("children"))
    product: dict = {
        "name": _PRODUCT,
        "role": "продукт",
        "description": "Продукт этого репозитория: витрина, заказы и биллинг.",
        # Свой продукт — это и есть репозиторий прогона, поэтому repo носит он.
        "source": {"repo": f"github.com/org/{_PRODUCT}"},
        "children": root["children"],
    }
    for child in product["children"]:
        _drop_repo(child)
    root["children"] = [
        product,
        # Заглушка соседа — ровно как учит раздел П1: только имя продукта и сетевое
        # имя, по которому мы к нему ходим.
        {"name": _NEIGHBOUR, "source": {"host": _NEIGHBOUR}},
    ]
    doc["edges"].append(
        {
            "from": "orders",
            "to": _NEIGHBOUR,
            "label": "передаёт заказ в доставку",
            "technology": "HTTP",
        }
    )
    return doc


def example_yaml(depth: int = 3, multi_product: bool = False) -> str:
    """Пример документа для промпта. depth=2 — без слоя компонентов (children
    контейнеров вырезаются), чтобы пример не противоречил инструкции.

    multi_product — федеративная укладка (_federated). ⚠ Порядок обязателен: сначала
    режем компоненты, потом оборачиваем в продукт. Иначе depth<3 срезал бы детей
    самого контейнера-продукта, и от примера остался бы один продукт без начинки;
    правило П1 «слои отсчитывай от контейнера-продукта» соблюдается ровно этим
    порядком."""
    doc = copy.deepcopy(_EXAMPLE_DOC)
    if depth < 3:
        for root in doc["nodes"]:
            for container in root.get("children", []):
                container.pop("children", None)
    if multi_product:
        doc = _federated(doc)
    return yaml.safe_dump(
        doc, allow_unicode=True, sort_keys=False, default_flow_style=False, width=4096
    )


