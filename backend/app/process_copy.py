"""Дублирование бизнес-процесса: копия пишется СТРОКАМИ, а не оркестрацией ручек.

Прежде копию собирал фронт поверх ПУБЛИЧНЫХ ручек — и терял ровно то, что эти ручки
сознательно отвергают:
  • непривязанного участника (ParticipantCreate требует node_id, а имя участника
    берётся ИЗ УЗЛА — поля имени в payload нет вовсе);
  • повисший шаг (не-самосообщение без связи) — 422 «Не указана связь»;
  • шаг-ответ на канале, который УЖЕ ПОСЛЕ создания шага стал асинхронным: у такого
    канала плеча «ответ» нет, и create_message его отвергает, хотя в оригинале шаг
    живёт (invalid_reason=leg_gone — расхождение, которое видно, а не исчезает);
  • фрагмент: create_fragment считал шаги в охвате уже поредевшей копии и валил
    дублирование на полпути, без отката — оставалась полусобранная копия.
Ослаблять публичные ручки нельзя: их 422 — инварианты («сначала привяжите участника»).
Значит копировать надо на уровне строк: копия переносит РОВНО ТО, ЧТО ЕСТЬ, включая
незадокументированность, — тем же способом, что и копия проекта (app/projects.py).

ЧТО именно переносится — объявлено в app/copy_plan.py (по умолчанию копируется всё,
кроме объявленного своим/пересчитываемым); здесь только порядок вставки и карта
«старый id участника → новый». Своей декларации процессным моделям не понадобилось:
они уже в COPY_PLAN, потому что их копирует копия проекта.
"""

import uuid

from sqlalchemy.orm import Session

from app.copy_plan import copy_row
from app.models.business_process import BusinessProcess


def duplicate_process(db: Session, proc: BusinessProcess) -> BusinessProcess:
    """Копия процесса в ТОМ ЖЕ проекте, одной транзакцией (коммит — на вызывающей
    стороне: полусобранной копии после ошибки не остаётся).

    Порядок шагов (order) переносится БЕЗ пересчёта — иначе разъехались бы границы
    фрагментов: фрагмент адресует диапазон позиций, а рендер считает строку РАНГОМ
    (числом шагов с меньшим order). Раз переносятся ВСЕ шаги, ранги в копии те же.
    """
    copy = copy_row(
        proc,
        id=uuid.uuid4(),
        # project_id объявлен own («значение назначает копировщик»), а не «обязательно
        # другое»: дублирование живёт внутри проекта.
        project_id=proc.project_id,
        # Область — тот же узел той же схемы: перемэппивать нечего (в отличие от копии
        # проекта, где узлы новые).
        scope_node_id=proc.scope_node_id,
    )
    # Имя — единственное, чем копия отличается от источника. Ставим ПОСЛЕ сборки:
    # copy_row намеренно не даёт подменять колонки-данные (иначе список исключений
    # снова стал бы ручным перечнем «что копировщику можно переписать»).
    copy.name = f"{proc.name} (копия)"
    db.add(copy)
    db.flush()  # процесс существует до участников/шагов/фрагментов (FK process_id)

    # Карта участников: концы шагов обязаны вести на участников КОПИИ.
    partmap: dict[uuid.UUID, uuid.UUID] = {}
    for part in list(proc.participants):
        partmap[part.id] = uuid.uuid4()
        db.add(
            copy_row(
                part,
                id=partmap[part.id],
                process_id=copy.id,
                # Узел тот же (копируем внутри проекта); у непривязанного участника
                # его нет — едет NULL, а ИМЯ участник несёт в себе (оно заморожено на
                # момент заведения и за переименованием узла не следует, поэтому
                # брать его у узла нельзя — так копия и портила имена).
                node_id=part.node_id,
            )
        )
    db.flush()  # участники существуют до шагов (FK from/to_participant_id)

    for msg in list(proc.messages):
        db.add(
            copy_row(
                msg,
                id=uuid.uuid4(),
                process_id=copy.id,
                # Повисший шаг остаётся повисшим, самосообщение — самосообщением
                # (оба конца ведут на одного участника), ответ на ставшем асинхронным
                # канале переносится как есть: копия обязана повторять источник.
                edge_id=msg.edge_id,
                from_participant_id=partmap[msg.from_participant_id],
                to_participant_id=partmap[msg.to_participant_id],
            )
        )

    fragmap: dict[uuid.UUID, uuid.UUID] = {}
    for frag in list(proc.fragments):
        fragmap[frag.id] = uuid.uuid4()
        db.add(copy_row(frag, id=fragmap[frag.id], process_id=copy.id))
    db.flush()  # фрагменты существуют до ветвей (FK fragment_id)

    for frag in list(proc.fragments):
        for branch in frag.branches:
            db.add(copy_row(branch, id=uuid.uuid4(), fragment_id=fragmap[frag.id]))
    db.flush()
    return copy
