"""Промпт агенту на описание КОНФИГУРАЦИИ сервиса (BYOA, Ф3 plan-config-docs.md).

Третий промпт семейства «факты о узле» после data_prompt (структура БД) и
channels_prompt (каналы брокера). Устройство общее: структура записями, адрес узла
ведущим комментарием, перечень допустимых адресов подставляется из проекта.

Отличие от каналов — в том, ГДЕ это запускать. У брокера нет репозитория-владельца, и
промпт каналов велит прогонять задачу в каждом репозитории, который в брокер ходит.
У конфигурации владелец всегда однозначен: параметр читает КОД СЕРВИСА, значит и
описывается он в репозитории этого сервиса. Один прогон — один сервис.

⚠️ ГЛАВНОЕ ПРАВИЛО ЭТОГО ПРОМПТА — ЗАПРЕТ ЗНАЧЕНИЙ. Агент, читающий конфигурацию,
неизбежно наткнётся на `.env` с паролями и токенами, а модели в этом проекте измеренно
ненадёжны в дисциплине правил (эпик разведки: иллюстрация из промпта утекла прямо в
данные и дала 29 % мусора). Поэтому запрет держится не только текстом правила, но и
САМИМ ПРИМЕРОМ: в образце формата стоит секретный параметр с пустым дефолтом и
подписью, почему он пуст. Пример сильнее правила — здесь это работает на нас.

Зависимости («какая развилка от ручки зависит») в пакет НЕ входят: они живут пометками
«зависит от:» в тексте схем логики (§5 плана) — промпт говорит это прямо, иначе агент
по привычке пришлёт раздел, который некуда деть.
"""

# Адрес для примера, когда подставить нечего (узлов-сервисов в проекте нет).
_FALLBACK_ADDR = "Платформа / Платежи"


def _address_lines(service_paths: list[str]) -> tuple[str, str]:
    """Строка про узлы-сервисы проекта + адрес для примера формата.

    Тот же приём, что у каналов: один узел — в примере стоит ровно он, места для
    выдумки не остаётся; ни одного — говорим честно (урок Н8: слепой адрес блокирует
    пакет целиком, и раунд переписки уходит на угадывание).
    """
    if not service_paths:
        return (
            "В проекте ещё нет узла-сервиса — сначала создайте его; без адреса "
            "параметры уедут к объекту, со страницы которого открыто окно.",
            _FALLBACK_ADDR,
        )
    if len(service_paths) == 1:
        return (
            f"Узел-сервис в этом проекте один — «{service_paths[0]}»: пиши ровно "
            "этот адрес.",
            service_paths[0],
        )
    listed = ", ".join(f"«{p}»" for p in service_paths)
    return (
        f"Узлы-сервисы этого проекта: {listed}. Адрес бери ДОСЛОВНО из этого перечня — "
        "других сервисов в проекте нет. Один прогон описывает конфигурацию ОДНОГО "
        "сервиса; в репозитории живут два — сделай два файла, у каждого свой адрес.",
        service_paths[0],
    )


def build_config_prompt(service_paths: list[str]) -> str:
    """Собрать текст промпта. service_paths — полные пути узлов-сервисов проекта
    (shape=service) в терминах импорта: они и есть допустимые адреса владельца."""
    nodes_line, example_addr = _address_lines(service_paths)

    return f"""# ArchMap · описание конфигурации сервиса

Опиши ПАРАМЕТРЫ КОНФИГУРАЦИИ сервиса — переменные окружения, флаги, настройки, —
которые читает код ЭТОГО репозитория. Итог: файлы в каталоге `archmap-docs/`, которые
человек загрузит в ArchMap.

## Значения не выписывать (главное правило)

В ArchMap едет ПЕРЕЧЕНЬ РУЧЕК, а не их значения. Значения разные в каждой среде и
часто секретны, а ArchMap не хранилище секретов.

- НЕ выписывай ничего, что похоже на живое значение: пароли, токены, ключи, строки
  подключения, адреса конкретных хостов и бакетов. Это правило сильнее всех
  остальных: увидел в `.env` строку с секретом — берёшь из неё ТОЛЬКО ИМЯ.
- Поле `default` — это дефолт ИЗ КОДА: второй аргумент `getenv`, значение поля в
  классе настроек, значение из `.env.example`, дефолт флага CLI. Дефолта в коде нет —
  оставь поле пустым, это законный и обычный ответ.

## Что делать

1. Найди чтение конфигурации: `os.getenv`/`os.environ`, `process.env`, классы настроек
   (pydantic Settings, dataclass конфига, viper, Spring `@Value`/`@ConfigurationProperties`),
   разбор флагов CLI (argparse, cobra, flag), обращения к секрет-менеджеру по имени
   ключа. Ищи ВСЕ места чтения, а не только один конфиг-модуль: часть ручек читается
   прямо в коде рядом с развилкой.
2. Дополни перечень объявлениями: `.env.example`, `values.yaml` и `templates/` чарта,
   ConfigMap и Secret в манифестах k8s, `environment:` в docker-compose, секции
   `[tool.*]`/`settings.py`, документация вроде `docs/configuration.md`. Из Secret
   берётся ТОЛЬКО ИМЯ КЛЮЧА.
3. На каждую ручку ответь на вопрос «ЧТО ОНА ПЕРЕКЛЮЧАЕТ» — по МЕСТУ ИСПОЛЬЗОВАНИЯ,
   а не по имени. Имя подсказывает, но точный ответ даёт развилка в коде: «включает
   новый расчёт корзины», «сколько раз повторить запрос к банку». Пересказ имени
   своими словами («уровень логирования — уровень логирования») бесполезен: такую
   строку лучше оставить без описания.
4. Сложи результат в файлы `archmap-docs/<что-угодно>.yaml` по формату ниже.

## Куда адресовать

Адрес узла-сервиса пиши КОММЕНТАРИЕМ первой строкой файла: «# archmap-node: <адрес>»,
именно с решёткой. Без неё строка станет обычным YAML-ключом, адреса ArchMap не увидит.
В этой строке — только адрес: хвост-пояснение после него станет частью адреса.
{nodes_line}

## Формат файла

```yaml
# archmap-node: {example_addr}
config:
  - name: FEATURE_NEW_CHECKOUT
    type: bool
    required: false
    default: "false"
    description: включает новый расчёт корзины вместо legacy-калькулятора
  - name: RETRY_TIMEOUT
    type: duration
    required: false
    default: 30s
    description: сколько ждать перед повтором запроса к банку
  - name: DATABASE_URL
    type: string
    required: true
    default: ""                 # СЕКРЕТ: имя есть, значения нет и быть не должно
    description: основное хранилище заказов
```

`type` — тип значения как в коде: «string», «int», «bool», «duration», «json».
Перечень не закрытый: пиши то, что видно, или оставь пустым.

## Правила

- Имена бери ДОСЛОВНО из кода: «FEATURE_NEW_CHECKOUT», если константа называется так,
  а не «Флаг новой корзины». По этому имени ArchMap сшивает параметр с пометками
  «зависит от:» в схемах логики, поэтому регистр и подчёркивания важны.
- `required: true` — только когда без параметра код падает или дефолта нет вовсе.
  Есть дефолт — значит не обязателен.
- Не заводи «параметрами» то, что конфигурацией не является: константы кода, которые
  ниоткуда не читаются, поля запроса, аргументы функций.
- Одна ручка — одна строка. Если один и тот же параметр читается в нескольких местах,
  это по-прежнему одна строка.
- Какая развилка от параметра зависит — описывается НЕ здесь, а пометкой
  «зависит от: ИМЯ» в схеме логики нужной операции: раздела для этого в формате нет.
- ЛЮБОЕ значение, внутри которого есть двоеточие с пробелом («таймаут: секунды»),
  бери в двойные кавычки — самая частая причина битого YAML.
- Ничего не удаляй и не «подчищай»: чего в файле нет, то в ArchMap останется как было.
"""
