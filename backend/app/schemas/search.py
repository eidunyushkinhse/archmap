"""Контракт поиска по знанию проекта (GET /api/v1/search).

Поиск сделан для ИИ-агента, разбирающего инцидент: на вход — сырая строка лога,
на выход — адреса мест, где это знание записано, и id для следующего шага
(открыть схему, карточку объекта, процесс). Логика матчинга — app/search.py.
"""

import uuid
from typing import Literal

from pydantic import BaseModel

# Вид единицы поиска. Источник правды контракта — этот Literal (фронтовый тип
# генерируется из него). Построчные виды — doc и spec: у них есть line_no.
SearchKind = Literal[
    "node",  # объект: имя, описание, роль, технология
    "doc",  # схема логики: заголовок (имя и эндпоинт) либо строка тела
    "spec",  # строка OpenAPI-спеки объекта
    "table",  # таблица БД: имя, описание
    "column",  # колонка таблицы: имя, тип, описание
    "channel",  # канал брокера: имя, группа, описание
    "field",  # поле сообщения канала
    "param",  # параметр конфигурации: имя, описание, дефолт
    "process",  # бизнес-процесс: имя
    "step",  # шаг процесса: подпись
]


class SearchHit(BaseModel):
    """Одна находка: адрес, id для перехода, совпавшая строка и её счёт."""

    kind: SearchKind
    # Адрес. У процесса и шага объекта нет — они принадлежат проекту целиком.
    # Поля без дефолтов намеренно: в генерате фронта они обязательные (null, а не
    # «может не прийти»).
    node_id: uuid.UUID | None
    node_path: str | None
    # Имя схемы, таблицы (с колонкой), канала (с полем), параметра или процесса;
    # у объекта и спеки — имя объекта и «OpenAPI».
    title: str
    # Id для перехода — какие применимы: схема (у doc и у шага, привязанного к
    # схеме), процесс и шаг.
    doc_id: uuid.UUID | None
    process_id: uuid.UUID | None
    message_id: uuid.UUID | None
    # Номер строки (с 1) у построчных видов: тело схемы и спека. У заголовка схемы
    # (имя и эндпоинт) номера нет.
    line_no: int | None
    # Совпавшая строка, обрезанная до ~200 символов вокруг совпадения.
    snippet: str
    score: float
    # Токены ЗАПРОСА, нашедшие пару в строке (после нормализации), по весу.
    matched: list[str]
    # Сколько ещё строк этой же схемы (или спеки) прошло порог, но не показано:
    # из одной схемы выдача берёт не больше трёх лучших. Одинаково у всех
    # показанных строк группы; у непострочных видов всегда 0.
    more_in_group: int = 0


class SearchResponse(BaseModel):
    query: str
    # Значимые токены запроса, по которым шёл поиск (после стоп-листа).
    tokens: list[str]
    # Сколько единиц прошло порог — до капа на схему и до limit.
    total: int
    hits: list[SearchHit]
