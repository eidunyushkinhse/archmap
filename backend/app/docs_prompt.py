"""Универсальный промпт «Доки от агента» (BYOA-дозаливка, этап 2 plan-agent-docs.md).

Пользователь копирует промпт из модалки открытого проекта и запускает СВОИМ
агентом в корне репозитория сервиса. В промпт ВЛОЖЕН срез схемы (build_export):
пути узлов из него — адреса для манифеста. Агент складывает в репозиторий пакет
archmap-docs/ (manifest.yaml + файлы спек; спеки копируются ИНСТРУМЕНТОМ, не
перепечатываются — окно вывода слабой модели портит большие тексты). Писан под
слабую модель: детерминированная процедура, жёсткий контракт вывода, встроенный
пример, чек-лист самопроверки (уроки стресс-теста repo-import).

Пример хранится ДАННЫМИ и дампается в YAML — тест кормит его в parse_manifest,
так что промпт физически не может протухнуть относительно формата манифеста.
"""

import copy

import yaml


class _Dumper(yaml.SafeDumper):
    """Свой дампер (как в export.py): не трогаем глобальный реестр PyYAML."""


def _str_representer(dumper: yaml.Dumper, data: str) -> yaml.Node:
    # Многострочный mermaid печатаем литеральным блоком (|) — пример молча учит
    # агента правильному стилю: внутри блока кавычки/двоеточия не нужны. Строки
    # с двоеточием/решёткой — В ДВОЙНЫХ кавычках (дефолт PyYAML — одинарные, а
    # правило промпта говорит про двойные; пример не должен противоречить).
    if "\n" in data:
        style = "|"
    elif ": " in data or data.endswith(":") or "#" in data:
        style = '"'
    else:
        style = None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_representer)

# ── Встроенный пример (данные, не текст) ─────────────────────────────────────
# Демонстрирует все конвенции: полный путь и голое уникальное имя в node,
# operation-схема с полем operation, воркер с двоеточием в имени (дампер
# закавычит — молчаливый урок кавычек), обзорная схема, file-референс спеки
# с origin, литеральные блоки mermaid с подписями в ["…"].
_EXAMPLE_MANIFEST: dict = {
    "docs": [
        {
            "node": "Ярмарка / orders",
            "logic": [
                {
                    "name": "POST /orders",
                    "kind": "operation",
                    "operation": "POST /orders",
                    "mermaid": (
                        "graph TD\n"
                        '  A["Приём запроса"] --> B["Валидация корзины"]\n'
                        '  B --> C{"Товары в наличии?"}\n'
                        '  C -- да --> D["Создать заказ в orders-db"]\n'
                        '  C -- нет --> E["409: конфликт наличия"]\n'
                        '  D --> F["Событие order.created в events"]'
                    ),
                },
                {
                    "name": "Крон: выставление счетов",
                    "kind": "worker",
                    "mermaid": (
                        "graph TD\n"
                        '  A["Раз в минуту"] --> B["Выбрать заказы без счёта"]\n'
                        '  B --> C["Запросить оплату в payments"]\n'
                        '  C --> D["Отметить заказ оплаченным"]'
                    ),
                },
            ],
            "openapi": {"file": "orders-api.yaml", "origin": "generated"},
        },
        {
            "node": "orders-db",
            "logic": [
                {
                    "name": "Схема хранения",
                    "kind": "overview",
                    "mermaid": (
                        "graph LR\n"
                        '  T1["orders"] --> T2["order_items"]\n'
                        '  T1 --> T3["order_status_log"]'
                    ),
                }
            ],
        },
    ]
}


def example_manifest(include: str = "both") -> str:
    """Пример манифеста для промпта. include=logic — без секций openapi,
    include=api — только записи со спекой (без logic), чтобы пример не
    противоречил инструкции."""
    doc = copy.deepcopy(_EXAMPLE_MANIFEST)
    if include == "logic":
        for entry in doc["docs"]:
            entry.pop("openapi", None)
    elif include == "api":
        doc["docs"] = [e for e in doc["docs"] if "openapi" in e]
        for entry in doc["docs"]:
            entry.pop("logic", None)
    return yaml.dump(
        doc,
        Dumper=_Dumper,
        allow_unicode=True,
        sort_keys=False,
        default_flow_style=False,
        width=4096,
    )


_LANG_LINE = {"ru": "русский", "en": "английский (English)"}


def build_docs_prompt(
    export_slice: str,
    include: str = "both",
    lang: str = "ru",
    hints: str | None = None,
    target: str | None = None,
) -> str:
    """Собрать текст промпта. export_slice — YAML среза схемы (build_export
    всего проекта или поддерева): пути узлов в нём — адреса для манифеста
    (срез поддерева даёт пути от его корня — резолвер дозаливки понимает
    однозначный хвост пути, как и импорт схемы). target — гранулярный режим
    «по одной схеме»: фокусирует агента на одном воркере/эндпоинте."""
    with_logic = include in ("logic", "both")
    with_api = include in ("api", "both")
    lang_line = _LANG_LINE.get(lang, _LANG_LINE["ru"])
    lang_note = (
        ""
        if lang == "ru"
        else " Пример ниже написан по-русски — в своём выводе используй выбранный язык."
    )

    logic_block = (
        """
### Схемы логики (logic)
- Обойди точки входа сервиса: HTTP-роутеры/хэндлеры, консьюмеры очередей, кроны и фоновые воркеры (main.*, файлы роутеров, конфиги celery/cron/systemd).
- На каждую ЗНАЧИМУЮ API-операцию, которую узел САМ ОБРАБАТЫВАЕТ (его входящий API), — схема kind: operation с полем operation: «METHOD /путь»; имя схемы — тоже «METHOD /путь».
- Сценарии узла-КЛИЕНТА (страницы и действия фронтенда, вызовы чужих API) оформляй kind: overview с человеческим именем сценария; поле operation у них не заполняй — оно адресует операцию собственного API узла.
- На каждый фоновый процесс — схема kind: worker.
- Обзорную схему сервиса целиком (kind: overview) добавляй одну и только если она даёт что-то сверх операционных.
- Не больше 12 схем на узел; каждая схема обозрима (примерно до 30 вершин) — крупный сценарий дели на несколько схем, а не рисуй монстра.
- Язык схем — ТОЛЬКО mermaid flowchart (graph TD или graph LR). Никаких sequenceDiagram/classDiagram/markdown. Подписи вершин — в квадратных скобках с кавычками: A["Проверяет корзину"].
- Схема описывает РЕАЛЬНЫЙ поток кода: ветвления, обращения к БД/брокерам/другим сервисам. Не рисуй «как наверное работает».
"""
        if with_logic
        else ""
    )

    api_block = (
        """
### OpenAPI-спека (openapi)
Спека описывает API, который узел САМ ПРЕДОСТАВЛЯЕТ (его входящие операции). Узел без собственного HTTP API (фронтенд, воркер, БД) — ключ openapi для него не пиши вовсе; спека сервиса, который он лишь вызывает, принадлежит тому сервису.
Одна спека на сервис. Добывай по ранжиру и фиксируй происхождение в origin:
1. В репозитории уже лежит готовая спека (openapi.yaml, swagger.json, api/*.yaml) — СКОПИРУЙ файл в пакет командой (cp), НЕ перепечатывай содержимое, origin: found.
2. Фреймворк умеет отдать спеку — сгенерируй её В ФАЙЛ командой (FastAPI: python -c "import json; from app.main import app; print(json.dumps(app.openapi()))" > archmap-docs/<сервис>-api.json; springdoc: GET /v3/api-docs; swagger-jsdoc и аналоги), origin: generated.
3. Ни того ни другого — синтезируй МИНИМАЛЬНУЮ честную спеку по коду роутеров: только реально существующие пути/методы/основные параметры и ответы. Ничего не выдумывай. origin: synthesized.
Файл спеки положи рядом с манифестом, в манифесте сошлись на него по имени: openapi: {file: имя-файла, origin: ...}. Только мелкую синтезированную спеку (до ~100 строк) можно писать инлайном: openapi: {inline: |, origin: synthesized}.
"""
        if with_api
        else ""
    )

    checklist: list[str] = ["manifest.yaml — синтаксически валидный YAML (отступы — два пробела)."]
    checklist.append(
        "Каждый node взят ДОСЛОВНО из среза схемы: полный путь, уникальное имя "
        "или однозначный хвост пути."
    )
    if with_logic:
        checklist.append(
            "Имена схем уникальны в пределах узла; у схем kind: operation заполнено поле operation."
        )
        checklist.append('mermaid каждой схемы — flowchart (graph TD/LR), подписи вершин в ["…"].')
    if with_api:
        checklist.append(
            "Файлы спек скопированы/сгенерированы командами, НЕ перепечатаны вручную; "
            "у каждой спеки указан origin."
        )
        checklist.append(
            "openapi и operation-схемы описывают ВХОДЯЩИЙ API узла; у узла без "
            "собственного API ключа openapi нет совсем."
        )
    checklist.append(
        "Значения манифеста с двоеточием, решёткой или кавычками внутри — в двойных кавычках "
        "(текст mermaid — всегда литеральным блоком «mermaid: |»)."
    )
    checklist.append("Задокументированы только узлы, чью реализацию видно в ЭТОМ репозитории.")
    checklist_text = "\n".join(f"{i + 1}. {line}" for i, line in enumerate(checklist))

    hints_block = (
        f"\n## Дополнительные указания пользователя (приоритетны)\n{hints.strip()}\n"
        if hints and hints.strip()
        else ""
    )

    # Гранулярный режим «по одной схеме»: фокус на одном воркере/эндпоинте
    # (крупные монолиты, которые агенту не переварить за один заход).
    target_block = (
        "\n## Фокус этого прогона (приоритетнее всего остального)\n"
        f"В этот раз опиши ТОЛЬКО «{target.strip()}» — ОДНУ схему логики: этот воркер "
        "или эндпоинт. kind определи по смыслу: operation — для обработчика входящего "
        "API узла (заполни поле operation: «METHOD /путь», имя схемы — тоже «METHOD /путь»); "
        "worker — для фонового процесса (имя — имя класса/функции-обработчика). "
        "Другие схемы в манифест НЕ добавляй.\n"
        if target and target.strip()
        else ""
    )

    what = (
        "схемы внутренней логики и OpenAPI-спеки"
        if include == "both"
        else ("схемы внутренней логики" if include == "logic" else "OpenAPI-спеки")
    )

    return f"""Ты — ИИ-агент с доступом к файлам репозитория и терминалу.
Задача: подготовь {what} для сервисов, чей код лежит в ЭТОМ репозитории. Архитектурная схема системы уже создана в ArchMap — ниже её срез. Схему НЕ меняй и не пересобирай: результат — ПАКЕТ ФАЙЛОВ с документами, привязанными к УЖЕ СУЩЕСТВУЮЩИМ узлам схемы.
{target_block}
## Срез схемы (адреса узлов)
```yaml
{export_slice.rstrip()}
```
Поле node в манифесте — адрес узла из этого среза: путь с разделителем « / » ДОСЛОВНО, либо уникальное имя узла, либо однозначный хвост пути. Ничего не переименовывай и не переводи.

## Что документировать
Только узлы, чью реализацию видишь в ЭТОМ репозитории (обычно один сервис, его компоненты и его БД). Узлы других репозиториев пропусти — их задокументируют прогоны в их репозиториях. Если своего сервиса в срезе нет — НЕ добавляй его в манифест; пропусти и скажи об этом в финальном ответе.
{logic_block}{api_block}
## Формат результата — пакет archmap-docs/
Создай в корне репозитория папку archmap-docs/:
- archmap-docs/manifest.yaml — манифест (пример ниже);
- рядом — файлы спек, на которые манифест ссылается по имени.
Пользователь загрузит все файлы папки в ArchMap разом.

Пример manifest.yaml:
```yaml
{example_manifest(include)}```
ВАЖНО: значение с двоеточием, решёткой или кавычками внутри оборачивай в двойные кавычки; текст mermaid всегда пиши литеральным блоком «mermaid: |» с отступом.
Язык подписей схем и имён — {lang_line}. Ключи YAML и значения kind/origin — латиницей ровно как в примере.{lang_note}

## Честность
- У каждого документа — основание в коде ЭТОГО репозитория. Ничего не добавляй «для полноты».
- Не уверен в ветке сценария или эндпоинте — не описывай; отметь сомнение в финальном ответе.

## Перед завершением проверь себя
{checklist_text}

В финальном ответе пользователю кратко перечисли: какие узлы задокументировал, сколько схем{", откуда взята спека (origin)" if with_api else ""}, что пропустил и почему.
Если пользователь пришлёт список замечаний валидатора — исправь пакет и сообщи, какие файлы изменились.
{hints_block}"""
