"""Универсальный промпт «Доки от агента» (BYOA-дозаливка, этап 2 plan-agent-docs.md).

Пользователь копирует промпт из модалки открытого проекта и запускает СВОИМ
агентом в корне репозитория сервиса. В промпт ВЛОЖЕН срез схемы (build_export):
пути узлов из него — адреса для схем. Агент складывает в репозиторий пакет
archmap-docs/: по файлу .mmd на схему логики (метаданные — ведущими строками
«%% archmap-*» внутри самого файла) и файл спеки, если её просили. Файла-описи
больше нет — каждый файл описывает себя сам (docs/plan-docs-mmd.md).

Спеки копируются ИНСТРУМЕНТОМ, не перепечатываются — окно вывода слабой модели
портит большие тексты. Промпт писан под слабую модель: детерминированная
процедура, жёсткий контракт вывода, встроенный образец, чек-лист самопроверки
(уроки стресс-теста repo-import).

Образец файла хранится ДАННЫМИ в mmd_header и парсится обратно тестом, поэтому
промпт физически не может протухнуть относительно формата. С пивота §9
docs/plan-db-docs.md образец несёт и пометку обращений («читает:/пишет:» в подписи
шага) — её тем же тестом разбирает наш parse_data_refs: обращения к данным едут в
ЭТОМ артефакте, отдельного раздела и отдельного пакета для них нет.
"""

from app.mmd_header import example_mmd

_LANG_LINE = {"ru": "русский", "en": "английский (English)"}


def build_docs_prompt(
    export_slice: str,
    include: str = "both",
    lang: str = "ru",
    hints: str | None = None,
    target: str | None = None,
) -> str:
    """Собрать текст промпта. export_slice — YAML среза схемы (build_export
    всего проекта или поддерева): пути узлов в нём — адреса для манифеста
    (срез поддерева даёт пути от его корня — резолвер дозаливки понимает
    однозначный хвост пути, как и импорт схемы). target — гранулярный режим
    «по одной схеме»: фокусирует агента на одном воркере/эндпоинте."""
    with_logic = include in ("logic", "both")
    with_api = include in ("api", "both")
    lang_line = _LANG_LINE.get(lang, _LANG_LINE["ru"])
    lang_note = (
        ""
        if lang == "ru"
        else " Пример ниже написан по-русски — в своём выводе используй выбранный язык."
    )

    logic_block = (
        """
### Схемы логики — по файлу .mmd на схему
- Обойди точки входа сервиса: HTTP-роутеры/хэндлеры, консьюмеры очередей, кроны и фоновые воркеры (main.*, файлы роутеров, конфиги celery/cron/systemd).
- На каждую ЗНАЧИМУЮ API-операцию, которую узел САМ ОБРАБАТЫВАЕТ (его входящий API), — схема kind: operation с полем operation: «METHOD /путь»; имя схемы — тоже «METHOD /путь».
- Сценарии узла-КЛИЕНТА (страницы и действия фронтенда, вызовы чужих API) оформляй kind: overview с человеческим именем сценария; поле operation у них не заполняй — оно адресует операцию собственного API узла.
- На каждый фоновый процесс — схема kind: worker.
- Обзорную схему сервиса целиком (kind: overview) добавляй одну и только если она даёт что-то сверх операционных.
- Не больше 12 схем на узел; каждая схема обозрима (примерно до 30 вершин) — крупный сценарий дели на несколько схем, а не рисуй монстра.
- Язык схем — ТОЛЬКО mermaid flowchart (graph TD или graph LR). Никаких sequenceDiagram/classDiagram/markdown. Подписи вершин — в квадратных скобках с кавычками: A["Проверяет корзину"].
- Схема описывает РЕАЛЬНЫЙ поток кода: ветвления, обращения к БД/брокерам/другим сервисам. Не рисуй «как наверное работает».

#### Пометки данных в подписях шагов
Шаг работает с данными (SQL-запрос, вызов ORM, запись в кэш) — допиши в ПОДПИСЬ этой вершины отдельную строку через `<br>`: «читает: …» или «пишет: …». После маркера — таблица или таблица.колонка, несколько целей через запятую; оба маркера у одного шага — двумя строками. Так обращения к данным попадают в ArchMap: отдельного файла и отдельного раздела для них нет.
- Пример: `D["Создать заказ<br>читает: accounts.balance<br>пишет: orders, order_items"]`.
- Имена таблиц и колонок бери ДОСЛОВНО из кода миграций и ORM-моделей — по ним ArchMap находит таблицу в описании базы. Не переводи, не склоняй, не переименовывай.
- Колонки НЕ ВЫДУМЫВАЙ: если из кода операции не видно, какие поля тронуты (`SELECT *`, сохранение объекта целиком) — оставь одну таблицу, это законный и обычный ответ.
- «пишет» — ЛЮБОЕ изменение состояния: INSERT, UPDATE, DELETE, upsert. Всё остальное — «читает».
- Одноимённые таблицы в разных базах — добавь перед именем базу: «пишет: Каталог-БД / orders» (адрес узла базы из среза выше, разделитель « / »).
- Слова «читает:»/«пишет:» употребляй ТОЛЬКО как эту пометку: ArchMap читает любую такую строку буквально, и «читает: конфиг из файла» станет ошибкой «таблица не найдена».

Каждая схема — ОТДЕЛЬНЫЙ файл archmap-docs/<что-угодно>.mmd. Имя файла роли не играет (можно 01-create-order.mmd) — паспорт схемы идёт ВНУТРИ файла, ведущими строками-комментариями:
```
%% archmap-name: имя схемы (обязательно: под ним она и будет видна)
%% archmap-kind: overview | operation | worker
%% archmap-operation: METHOD /путь   (только для kind: operation)
%% archmap-node: адрес узла          (только если схема НЕ про основной сервис — см. ниже)
```
Mermaid строки на «%%» игнорирует, поэтому файл остаётся обычной диаграммой и открывается любым просмотрщиком."""
        if with_logic
        else ""
    )

    api_block = (
        """
### OpenAPI-спека
Спека описывает API, который узел САМ ПРЕДОСТАВЛЯЕТ (его входящие операции). У узла без собственного HTTP API (фронтенд, воркер, БД) спеки нет вовсе — спека сервиса, который он лишь вызывает, принадлежит тому сервису.
Одна спека на сервис. Добывай по ранжиру:
1. В репозитории уже лежит готовая спека (openapi.yaml, swagger.json, api/*.yaml) — СКОПИРУЙ файл в пакет командой (cp), НЕ перепечатывай содержимое. Происхождение: found.
2. Фреймворк умеет отдать спеку — сгенерируй её В ФАЙЛ командой (FastAPI: python -c "import json; from app.main import app; print(json.dumps(app.openapi()))" > archmap-docs/<сервис>-api.json; springdoc: GET /v3/api-docs; swagger-jsdoc и аналоги). Происхождение: generated.
3. Ни того ни другого — синтезируй МИНИМАЛЬНУЮ честную спеку по коду роутеров: только реально существующие пути/методы/основные параметры и ответы. Ничего не выдумывай. Происхождение: synthesized.
Первой строкой файла спеки (если это YAML) добавь комментарий с происхождением: «# archmap-origin: found | generated | synthesized». Если спека в JSON — комментарий не нужен, происхождение просто не будет показано.
"""
        if with_api
        else ""
    )

    checklist: list[str] = []
    if with_logic:
        checklist.append(
            "У каждого .mmd-файла есть строка «%% archmap-name» — без неё схема "
            "получит имя файла."
        )
        checklist.append(
            "Имена схем уникальны в пределах узла; у схем kind: operation заполнена "
            "строка «%% archmap-operation»."
        )
        checklist.append('Каждая схема — flowchart (graph TD/LR), подписи вершин в ["…"].')
        checklist.append(
            "У шагов, работающих с данными, есть строка «читает:»/«пишет:» с именами "
            "таблиц ДОСЛОВНО из кода; выдуманных колонок нет."
        )
        checklist.append(
            "«%% archmap-node» стоит ТОЛЬКО у схем не про основной сервис, и адрес "
            "взят ДОСЛОВНО из среза схемы."
        )
    if with_api:
        checklist.append(
            "Файл спеки скопирован/сгенерирован командой, НЕ перепечатан вручную; "
            "первой строкой YAML-спеки — комментарий с происхождением."
        )
        checklist.append(
            "Спека и operation-схемы описывают ВХОДЯЩИЙ API узла; у узла без "
            "собственного API спеки нет совсем."
        )
    checklist.append("Задокументированы только узлы, чью реализацию видно в ЭТОМ репозитории.")
    checklist.append("В финальном ответе перечислены ВСЕ созданные файлы — по именам.")
    checklist_text = "\n".join(f"{i + 1}. {line}" for i, line in enumerate(checklist))

    hints_block = (
        f"\n## Дополнительные указания пользователя (приоритетны)\n{hints.strip()}\n"
        if hints and hints.strip()
        else ""
    )

    # Гранулярный режим «по одной схеме»: фокус на одном воркере/эндпоинте
    # (крупные монолиты, которые агенту не переварить за один заход).
    target_block = (
        "\n## Фокус этого прогона (приоритетнее всего остального)\n"
        f"В этот раз опиши ТОЛЬКО «{target.strip()}» — ОДНУ схему логики: этот воркер "
        "или эндпоинт. kind определи по смыслу: operation — для обработчика входящего "
        "API узла (заполни поле operation: «METHOD /путь», имя схемы — тоже «METHOD /путь»); "
        "worker — для фонового процесса (имя — имя класса/функции-обработчика). "
        "Других схем НЕ создавай — в пакете должен быть ровно один .mmd-файл.\n"
        if target and target.strip()
        else ""
    )

    what = (
        "схемы внутренней логики и OpenAPI-спеки"
        if include == "both"
        else ("схемы внутренней логики" if include == "logic" else "OpenAPI-спеки")
    )

    # Из чего состоит пакет и нужен ли образец файла — зависит от того, что просят.
    if include == "logic":
        package_line = "по одному .mmd-файлу на каждую схему"
    elif include == "api":
        package_line = "файл спеки"
    else:
        package_line = "по одному .mmd-файлу на каждую схему и файл спеки"
    example_block = (
        f"\nОбразец .mmd-файла:\n```\n{example_mmd()}```\n" if with_logic else ""
    )
    # Первый узел среза — тот, для которого открыто окно: к нему всё и уезжает по
    # умолчанию, поэтому адрес нужен только «вбок» (компонент, БД сервиса).
    address_line = (
        "Схемы по умолчанию привязываются к ГЛАВНОМУ узлу этого среза — первому в списке. "
        "Если схема описывает не его, а вложенный узел (компонент, БД сервиса), добавь в файл "
        "строку «%% archmap-node: адрес»: путь с разделителем « / » ДОСЛОВНО, либо уникальное "
        "имя узла, либо однозначный хвост пути из среза. Ничего не переименовывай и не переводи."
        if with_logic
        else "Спека уезжает ГЛАВНОМУ узлу этого среза — первому в списке."
    )

    return f"""Ты — ИИ-агент с доступом к файлам репозитория и терминалу.
Задача: подготовь {what} для сервисов, чей код лежит в ЭТОМ репозитории. Архитектурная схема системы уже создана в ArchMap — ниже её срез. Схему НЕ меняй и не пересобирай: результат — ПАКЕТ ФАЙЛОВ с документами, привязанными к УЖЕ СУЩЕСТВУЮЩИМ узлам схемы.
{target_block}
## Срез схемы (адреса узлов)
```yaml
{export_slice.rstrip()}
```
{address_line}

## Что документировать
Только узлы, чью реализацию видишь в ЭТОМ репозитории (обычно один сервис, его компоненты и его БД). Узлы других репозиториев пропусти — их задокументируют прогоны в их репозиториях. Если своего сервиса в срезе нет — ничего не выдумывай: пропусти и скажи об этом в финальном ответе.
{logic_block}{api_block}
## Формат результата — пакет archmap-docs/
Создай в корне репозитория папку archmap-docs/ и сложи в неё {package_line}. Никакого файла-описи не нужно: каждый файл сам себя описывает. Пользователь загрузит файлы папки в ArchMap разом — перетаскиванием или вставкой текста.
{example_block}Язык подписей схем и имён — {lang_line}. Ключи шапки и значения kind — латиницей ровно как в примере.{lang_note}

## Честность
- У каждого документа — основание в коде ЭТОГО репозитория. Ничего не добавляй «для полноты».
- Не уверен в ветке сценария или эндпоинте — не описывай; отметь сомнение в финальном ответе.

## Перед завершением проверь себя
{checklist_text}

В финальном ответе пользователю перечисли СОЗДАННЫЕ ФАЙЛЫ по именам (это важно: файлы он будет переносить в ArchMap руками и должен видеть, что ничего не потерял), какие узлы задокументировал{", откуда взята спека" if with_api else ""}, что пропустил и почему.
Если пользователь пришлёт список замечаний валидатора — исправь пакет и сообщи, какие файлы изменились.
{hints_block}"""
