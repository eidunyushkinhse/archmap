# Кап перечня имён НА СЕМЬЮ (таблицы, каналы). Перечень — подсказка «пиши ровно эти
# имена», а не выгрузка структуры: на проекте в тысячу таблиц он вытеснил бы правила,
# ради которых промпт и написан. Узел, не влезший в остаток, называется строкой с
# числом: молча обрезанный перечень слабая модель считает ПОЛНЫМ и «чинит» по нему
# верные имена (тот же принцип «no silent caps», что у замечаний превью).
MAX_CATALOG_NAMES = 400


def _plural(n: int, one: str, few: str, many: str) -> str:
    """Русское склонение счётного слова (строка-заглушка не влезшего перечня)."""
    if n % 100 // 10 == 1:
        return many
    if n % 10 == 1:
        return one
    if 2 <= n % 10 <= 4:
        return few
    return many


def _catalog_block(
    catalog: dict[str, list[str]] | None,
    header: str,
    forms: tuple[str, str, str],
    where: str,
    rules: str,
) -> str:
    """Перечень «узел: имена» под заголовком + правила про имя вне перечня — или
    ПУСТАЯ строка.

    Пустой каталог (структуру ещё не описали) не оставляет в промпте следов: текст
    обязан деградировать до прежнего байт-в-байт, иначе агент увидит заголовок над
    пустотой и решит, что описанных имён нет вовсе. Правила тоже условны: «нет в
    перечне» бессмысленно там, где перечня не показали.
    """
    if not catalog:
        return ""
    left = MAX_CATALOG_NAMES
    lines: list[str] = []
    for path in sorted(catalog):
        names = sorted(dict.fromkeys(n for n in catalog[path] if n))
        if not names:
            continue
        if len(names) <= left:
            lines.append(f"  - {path}: {', '.join(names)}")
            left -= len(names)
        else:
            lines.append(
                f"  - {path}: {len(names)} {_plural(len(names), *forms)} — "
                f"перечень велик, {where}"
            )
    if not lines:
        return ""
    return f"{header}\n" + "\n".join(lines) + f"\n{rules}\n"


