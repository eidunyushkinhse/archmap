def test_промпт_даёт_процедуру_обхода_точек_входа():
    """Вывод 3 замера полноты (docs/qa-recon-completeness.md): разведка взяла 100%
    ядра тремя правилами, которых в промпте доков не было, и каждое стоило реальных
    пропусков — оборванное на середине чтение файла-списка (потеряны tornado и
    analytics), один метод из нескольких объявленных на строке (единственный класс,
    который не вылечил и скептик), маршруты в других файлах (потерян весь zilencer).

    Правила процедурные (найди, дочитай, выпиши, обойди), а не пожелания: в проекте
    работают именно такие — см. «Порядок обследования» в import_prompt.
    """
    prompt = build_docs_prompt(SLICE, include="logic")
    for marker in (
        "Обход — процедура, а не беглый просмотр",
        # 1) файл-список маршрутов дочитывается до конца
        "файл-СПИСОК маршрутов",
        "дочитай его ДО ПОСЛЕДНЕЙ СТРОКИ",
        # 2) одно объявление — несколько методов
        "часто несёт НЕСКОЛЬКО методов",
        "выпиши КАЖДЫЙ метод отдельной точкой входа, а не первый из списка",
        # 3) маршруты ниже по файлу и в других файлах
        "и ниже по файлу, и в ДРУГИХ файлах",
        "Найди ВСЕ такие файлы и обойди каждый",
    ):
        assert marker in prompt, marker

    # В окне спеки маршруты тоже обходят (тест ниже), но результатом там становятся
    # ключи спеки, а не схемы: логическая формулировка «точка входа = схема» туда не
    # протекает.
    assert "выпиши КАЖДЫЙ метод отдельной точкой входа" not in build_docs_prompt(
        SLICE, include="api"
    )


def test_окно_спеки_даёт_свою_процедуру_обхода_роутеров():
    """Тот же класс пропусков во втором месте: ветка «готовой спеки нет — синтезируй по
    коду роутеров» обходит те же файлы маршрутов, что и разведка точек входа, и теряет
    на них то же самое (вывод 3 замера, docs/qa-recon-completeness.md). Процедура из
    блока логики до этого окна не доезжает: в режиме «только спека» блока логики нет.

    Правила адаптированы, а не скопированы: результат ветки — пути и методы в спеке,
    поэтому «выпиши точку входа» превращается в «заведи ключ-операцию у пути», а обход
    чужих файлов маршрутов тянет за собой префикс подключения роутера.
    """
    api = build_docs_prompt(SLICE, include="api")
    both = build_docs_prompt(SLICE, include="both")
    for marker in (
        "Обход роутеров — процедура, а не беглый просмотр",
        # 1) файл-список маршрутов дочитывается до конца
        "дочитай его ДО ПОСЛЕДНЕЙ СТРОКИ",
        "молча уносит из раздела paths целые подсистемы",
        # 2) одно объявление — несколько методов (единственный класс пропусков, который
        # в замере не вылечил и скептик)
        "часто несёт НЕСКОЛЬКО методов",
        "заведи у пути ключ-операцию на КАЖДЫЙ объявленный метод",
        # 3) маршруты ниже по файлу и в других файлах — вместе с префиксом подключения
        "и ниже по файлу, и в ДРУГИХ файлах",
        "Найди ВСЕ такие файлы и внеси в спеку пути каждого",
        "вместе с префиксом, под которым роутер подключён",
    ):
        assert marker in api, marker
        assert marker in both, marker

    # Процедура висит на ветке СИНТЕЗА: у найденной и сгенерированной спеки роутеры не
    # обходят вовсе (файл копируют инструментом), и правила там были бы вредным шумом.
    assert api.index("Обход роутеров") > api.index("Происхождение: synthesized")

    # В окно логики правила спеки не протекают: там своя процедура, своими словами.
    assert "Обход роутеров" not in build_docs_prompt(SLICE, include="logic")


