def test_промпт_учит_пометкам_обращений():
    """Конвенция пометок (пивот §9 plan-db-docs.md) и её образец — в промпте логики.

    Главная гарантия — та же, что у шапки: пометку из ОБРАЗЦА разбирает наш же
    parse_data_refs. Разъезд здесь означал бы, что агента учат синтаксису, который
    ArchMap молча не читает.
    """
    prompt = build_docs_prompt(SLICE, include="logic")
    for marker in (
        "Пометки данных в подписях шагов",
        "«читает: …» или «пишет: …»",
        "ДОСЛОВНО из кода миграций",
        "Колонки НЕ ВЫДУМЫВАЙ",
        "ЛЮБОЕ изменение состояния",
        "Одноимённые таблицы в разных базах",
        # Маркер = обещание факта: проза после «читает:» тоже извлечётся
        "«читает: конфиг из файла» станет ошибкой",
        # Чек-лист самопроверки — последнее, что модель читает перед выводом
        "выдуманных колонок нет",
    ):
        assert marker in prompt, marker

    # Находки №2 и №7 полевого QA: пометки писала сессия, не читавшая DDL («action»
    # против таблицы «actions»), и помечала любой I/O — 46 алертов-шума на проект.
    for marker in (
        "Пометка — ТОЛЬКО про таблицы базы данных",
        "in-memory кэши и очереди, HTTP-вызовы пометками НЕ помечай",
        "из самой СХЕМЫ БД (DDL)",
        "«actions», если таблица называется actions",
        "открой DDL и проверь",
        "НЕ пиши пометку",
        # Чек-лист: сверка имён с DDL и периметр пометки
        "Имена в пометках сверены с DDL",
        "пометок на не-таблицах",
    ):
        assert marker in prompt, marker

    refs = {(r.ref, r.mode) for r in parse_data_refs(example_mmd())}
    assert refs == {
        ("accounts.balance", "read"), ("orders", "write"), ("order_items", "write"),
        # Событие в брокер — вторая семья пометок, и она в том же образце (§3
        # plan-broker-docs.md): иначе агент помечает публикацию словом «пишет:».
        ("orders.created", "publish"),
    }

    # В окне спеки пометкам учить нечему — схем логики там нет
    assert "пишет:" not in build_docs_prompt(SLICE, include="api")


def test_промпт_учит_пометкам_событий():
    """Конвенция каналов (§3 plan-broker-docs.md) — вторая семья пометок в том же
    промпте. Отдельные слова, а не синонимы «пишет:/читает:»: у событий своя
    семантика доставки и свой каталог, и «пишет: orders.created» ушло бы искать
    таблицу. Гарантия та же — пометка из ОБРАЗЦА разбирается нашим parse_data_refs
    (проверено в тесте выше).
    """
    prompt = build_docs_prompt(SLICE, include="logic")
    for marker in (
        "Пометки событий: публикует:/потребляет:",
        "«публикует: …» или «потребляет: …»",
        "Публикацию в топик помечай «публикует:», а не «пишет:»",
        # Периметр: без него агент помечает любой I/O — 46 алертов-шума на проект
        # (находка №7 полевого QA, класс тот же).
        "ТОЛЬКО про каналы брокеров",
        "очереди ВНУТРИ процесса",
        # Имена из головы — главный источник битых пометок (урок Н2). Правило пришито
        # к САМОМУ правилу, а не к его отголоску в чек-листе: одной формулировки в
        # конце промпта мало, слабая модель до неё уже напишет пометки.
        "Имена каналов бери ДОСЛОВНО из кода или конфига",
        "Точки, дефисы и версии в имени — норма",
        "НЕ пиши пометку",
        "Одноимённые каналы у разных брокеров",
        # Чек-лист — последнее, что модель читает перед выводом.
        "события помечены этими словами",
    ):
        assert marker in prompt, marker

    # В окне спеки схем логики нет — учить каналам нечему.
    assert "публикует:" not in build_docs_prompt(SLICE, include="api")


def test_промпт_запрещает_чинить_пометки_удалением():
    """Находка №2 полевого QA (docs/qa-sentry-brokers.md): по списку из ~7 битых
    пометок Haiku «починил» их удалением ВСЕХ 83 табличных — обратный индекс базы
    опустел, а превью стало «идеальным». Ампутация Х3 в новой одежде, и лечится тем
    же: правило «чини, а не удаляй» стоит в САМОЙ конвенции пометок, а не только в
    тексте кнопки замечаний (кнопку копируют не всегда, промпт — всегда).
    """
    prompt = build_docs_prompt(SLICE, include="logic")
    assert "УДАЛЯТЬ пометки нельзя" in prompt
    assert "удаление прячет факт, а не исправляет его" in prompt
    # Что делать вместо удаления — ОДНА цель, а не выбор из двух механик (находка №1
    # docs/qa-zulip-brokers.md: «имя ИЛИ квалификатор» дало колебательный контур —
    # квалификатор добавили, потом сняли, имя так и не сверили).
    assert "чини каждую ДОСЛОВНЫМ именем" in prompt
    assert "есть подсказка «похоже на …» — бери имя из неё" in prompt
    # Квалификатор остаётся, но с условием применения: он про омонимы, а не про
    # починку имени (у таблиц и каналов он свой).
    assert "«Узел-БД / таблица», «Брокер / канал»" in prompt
    assert "ТОЛЬКО когда одинаковое имя есть у РАЗНЫХ узлов" in prompt

    # В окне спеки пометок нет — и правила о них тоже.
    assert "УДАЛЯТЬ пометки нельзя" not in build_docs_prompt(SLICE, include="api")


# ── перечни описанных имён (Ф8а, находки №1 и №3 docs/qa-zulip-brokers.md) ─────
# Петля замечаний «чини именем ИЛИ квалификатором» слабую модель не лечила: два
# круга правок, 51 битая пометка как была. Цель должна содержать ОТВЕТ — перечень
# уже описанных имён стоит В САМОЙ конвенции пометок, до первой написанной пометки.


def test_перечень_описанных_имён_подставлен_в_конвенцию_пометок():
    prompt = build_docs_prompt(
        SLICE,
        include="logic",
        table_catalog={
            "Ярмарка / Хранилище": ["orders", "public.accounts"],
            "Ярмарка / Архив": ["audit_log"],
        },
        channel_catalog={"Ярмарка / Шина": ["orders.created"]},
    )

    # Имена перечислены по узлу на строку — и адресом узла, и дословными именами
    # (таблица с разделом — «раздел.имя», ровно как её видит резолвер пометок).
    assert "Таблицы, уже описанные в проекте, — пометки используют ТОЛЬКО эти имена" in prompt
    assert "- Ярмарка / Хранилище: orders, public.accounts" in prompt
    assert "- Ярмарка / Архив: audit_log" in prompt
    assert "Каналы, уже описанные у брокеров проекта" in prompt
    assert "- Ярмарка / Шина: orders.created" in prompt

    # Имени нет в перечне — ответ дан обоим случаям: сверить с DDL (имя ORM-класса
    # таблицей не является) и сказать вслух, что описание неполно.
    assert "ORM-класс Message обычно даёт таблицу вида app_message" in prompt
    assert "структура проекта неполна" in prompt
    assert "описание брокера неполно" in prompt
    # Находка №3: пометки на кэшах дают вечный unknown_table — у кэша структуры нет.
    assert "кэши, memcached, поисковые индексы без описанной структуры" in prompt

    # В окне спеки схем логики нет — и перечням там не место.
    assert "Таблицы, уже описанные в проекте" not in build_docs_prompt(
        SLICE, include="api", table_catalog={"Ярмарка / Хранилище": ["orders"]}
    )


def test_пустые_каталоги_не_оставляют_в_промпте_следов():
    """Деградация без следов: проект без описанной структуры получает ПРЕЖНИЙ текст.

    Заголовок над пустотой хуже отсутствия — он утверждает «описанных имён нет», и
    слабая модель сотрёт по нему верные пометки.
    """
    base = build_docs_prompt(SLICE, include="logic")

    assert build_docs_prompt(SLICE, include="logic", table_catalog={}, channel_catalog={}) == base
    # Узлы в каталоге есть, а имён у них нет — тот же случай «описывать нечего».
    assert (
        build_docs_prompt(
            SLICE,
            include="logic",
            table_catalog={"Ярмарка / Хранилище": []},
            channel_catalog={"Ярмарка / Шина": []},
        )
        == base
    )
    assert "уже описанные" not in base


def test_кап_перечня_называет_число_а_не_обрезает_молча():
    """Урезанный молча перечень слабая модель считает полным и «чинит» по нему
    верные имена — поэтому не влезший узел заменяется строкой со счётом."""
    много = [f"t{i}" for i in range(MAX_CATALOG_NAMES + 1)]
    prompt = build_docs_prompt(
        SLICE,
        include="logic",
        table_catalog={"Ярмарка / Большая": много, "Ярмарка / Малая": ["orders"]},
    )

    assert (
        f"- Ярмарка / Большая: {MAX_CATALOG_NAMES + 1} таблица — перечень велик, "
        "сверяйся со структурой на странице узла" in prompt
    )
    # Ни одного имени великого узла в промпте нет — именно это и значит «не обрезано
    # молча»: перечня как будто и не начинали.
    assert "t0" not in prompt
    # Остаток капа не съеден: узел, который влезает, перечислен целиком.
    assert "- Ярмарка / Малая: orders" in prompt


