@pytest.mark.parametrize("flow", ПОТОКИ)
def test_variant_skeptic_и_orchestrated(flow):
    skeptic = prompt_for_variant("skeptic", flow, БЛОК_А, system_name="Ярмарка")
    assert ПОРОГ_V1 in skeptic
    assert БЛОК_А not in skeptic  # строительного промпта в аудите нет
    # Standalone-скептик: отчёт кладётся в корень и передаётся строителю руками.
    assert "archmap-skeptic-report.md" in skeptic

    orch = prompt_for_variant("orchestrated", flow, БЛОК_А, system_name="Ярмарка")
    assert _между(orch, BLOCK_A_START, BLOCK_A_END) == f"\n{БЛОК_А}\n"
    # Внутри блока Б — скептик В ПЕТЛЕ (нумерованный отчёт), а не standalone-вариант.
    assert "archmap-orch/skeptic-report-<N>.md" in _между(orch, BLOCK_B_START, BLOCK_B_END)
