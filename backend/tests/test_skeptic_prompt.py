def test_разведка_главная_форма_отчёта_это_ПРОПУСК():
    """⚠ Р6 эпика: у разведки форма пропуска — не приписка в хвосте, а ОСНОВНАЯ форма.
    Замер: 17 верных пропусков и НОЛЬ ложных, системный пропуск (непрочитанный источник
    целиком) ловится 11/11. Спрятать эту форму в конец = отменить главный выигрыш."""
    формат = build_skeptic_prompt("recon").split("## Формат отчёта")[1]

    assert _есть(формат, "ГЛАВНАЯ форма — ПРОПУСК: в коде есть точка входа, которой в "
                         "перечне НЕТ")
    assert _есть(формат, "- в перечне нет операции «METHOD /путь», хотя код её объявляет — "
                         "<доказательство>")
    assert _есть(формат, "- в перечне нет воркера «имя очереди», хотя код или конфиг "
                         "развёртывания его запускает — <доказательство>")
