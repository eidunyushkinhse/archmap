"""Промпты аудита вторым агентом-скептиком (app/skeptic_prompt.py, Ф0 эпика).

Тесты структурные — по подстрокам-инвариантам: текст промпта проверить «на качество»
нельзя, но можно закрепить то, что выверено экспериментами и стоит денег при потере:

- порог уверенности V1 — ДОСЛОВНО (docs/qa-skeptic-threshold.md, 18 прогонов: V2 дал
  единственные ложные сомнения и провалил полноту). Ожидаемый текст здесь ЛИТЕРАЛ, а не
  импортированная константа: сверка константы с самой собой не поймала бы её правку;
- поимённые чек-листы слабых классов ПОТОКА — главный рычаг полноты (вывод 5 того же
  эксперимента), поэтому каждый поток обязан нести свой, а не общий;
- механика обёртки (docs/qa-orchestrator-experiment.md): маркеры блоков, дословность
  тел, гейт субагентов, cat/heredoc, кап двух кругов, правило маршрутизатора.
"""

