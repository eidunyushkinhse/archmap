def test_чек_листы_различаются_по_потокам():
    """Слабые классы у потоков разные, и промпт обязан называть ИХ, а не общие слова:
    универсальный чек-лист — это отсутствие чек-листа."""
    imp = build_skeptic_prompt("import")
    docs = build_skeptic_prompt("docs")
    data = build_skeptic_prompt("data")
    ch = build_skeptic_prompt("channels")
    rec = build_skeptic_prompt("recon")

    # Импорт: самый непойманный класс стенда (4/18) назван вместе с методом проверки.
    assert _есть(imp, "не один ли это процесс")
    assert "INSTALLED_APPS" in imp
    assert _есть(imp, "из манифестов")
    assert "SESSION_ENGINE" in imp  # «хранит X» — 9/18, тоже с методом
    # Каналы: канал без точки публикации/потребления в коде — выдумка.
    assert _есть(ch, "точка публикации или потребления")
    assert "CELERY_BROKER_URL" in ch  # владелец-брокер по коду, не по порядку перечня
    # Структура БД: abstract-класс ORM таблицей не является.
    assert "abstract" in data
    assert "app_message" in data
    # Доки: пометка обязана быть обращением ИМЕННО этого сценария.
    assert _есть(docs, "в ЭТОМ сценарии")
    assert "OpenAPI-спеки" in docs
    # Разведка: чек-лист строится вокруг того, что в замере РЕАЛЬНО сработало —
    # каждый источник до конца, непрочитанный источник целиком, несколько методов
    # одного объявления и фоновая работа вне кода сервиса.
    assert _есть(rec, "КАЖДЫЙ источник из раздела `sources`")
    assert _есть(rec, "Файлы-СПИСКИ маршрутов, которых в `sources` НЕТ ВОВСЕ")
    assert _есть(rec, "Непрочитанный источник ЦЕЛИКОМ")
    assert _есть(rec, "Объявления с НЕСКОЛЬКИМИ методами сразу")
    assert "cron.d" in rec and "puppet/ansible" in rec

    # И чек-листы не протекают друг в друга.
    assert not _есть(imp, "точка публикации или потребления")
    assert "INSTALLED_APPS" not in docs
    assert not _есть(data, "в ЭТОМ сценарии")
    assert not _есть(docs, "КАЖДЫЙ источник из раздела `sources`")
    assert "cron.d" not in imp


