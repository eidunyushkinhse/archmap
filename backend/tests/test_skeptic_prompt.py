# ── Оркестраторная обёртка ────────────────────────────────────────────────────

БЛОК_А = "СТРОИТЕЛЬНЫЙ ПРОМПТ\nвторая строка «с кавычками»\n"
БЛОК_Б = "ПРОМПТ СКЕПТИКА\n"


@pytest.mark.parametrize("flow", ПОТОКИ)
def test_маркеры_ровно_по_одному_разу_и_тела_дословны(flow):
    """Агент режет обёртку по маркерам: второе вхождение любого из них — обрубленное
    задание субагенту, молча и без ошибки."""
    w = build_orchestrated_prompt(БЛОК_А, БЛОК_Б, flow)

    for marker in (BLOCK_A_START, BLOCK_A_END, BLOCK_B_START, BLOCK_B_END):
        assert w.count(marker) == 1, marker
    # Срез между маркерами — ровно переданный текст (плюс переводы строк маркеров).
    assert _между(w, BLOCK_A_START, BLOCK_A_END) == f"\n{БЛОК_А}\n"
    assert _между(w, BLOCK_B_START, BLOCK_B_END) == f"\n{БЛОК_Б}\n"


@pytest.mark.parametrize("маркер", [BLOCK_A_START, BLOCK_A_END, BLOCK_B_START, BLOCK_B_END])
def test_маркер_в_теле_блока_это_ошибка(маркер):
    with pytest.raises(ValueError):
        build_orchestrated_prompt(f"промпт\n{маркер}\nхвост", БЛОК_Б, "import")
    with pytest.raises(ValueError):
        build_orchestrated_prompt(БЛОК_А, f"промпт\n{маркер}\nхвост", "import")


@pytest.mark.parametrize("flow", ПОТОКИ)
def test_обёртка_несёт_механику_петли(flow):
    """Что дало 5/5 механики на слабой модели (docs/qa-orchestrator-experiment.md):
    гейт субагентов, файловая передача через терминал, кап кругов, не-арбитраж."""
    w = build_orchestrated_prompt(БЛОК_А, БЛОК_Б, flow)

    # Гейт: без субагентов процедура бессмысленна — остановись, а не делай сам.
    assert _есть(w, "Ты — ОРКЕСТРАТОР")
    assert _есть(w, "Сам не исследуешь репозиторий и не пишешь документацию")
    assert _есть(w, "инструмент Task/Agent")
    assert _есть(w, "возьмите в ArchMap промпт без аудита")
    # ⚠ Перепечатка блоков Write-ом теряет типографские кавычки (замер эксперимента).
    assert "ЧЕРЕЗ ТЕРМИНАЛ" in w and "heredoc" in w
    assert _есть(w, "НЕ перенабирай текст блока руками")
    # Чистый каталог: файлы прошлого прогона заражают следующий.
    assert _есть(w, "Каталог уже есть — сначала УДАЛИ его целиком")
    # Петля и её кап.
    assert _есть(w, "Прочитай файл `archmap-orch/builder-prompt.txt`")
    assert _есть(w, "Прочитай файл `archmap-orch/skeptic-prompt.txt`")
    assert _есть(w, "у которого номер НАИБОЛЬШИЙ")
    assert "ПОДТВЕРЖДЕНО ВСЁ" in w
    assert _есть(w, "Больше ДВУХ кругов аудита не делай")
    # Починка: правило аудита, а не валидатора, и запрет выдумывать замену.
    assert _есть(w, "Это замечания АУДИТА по коду (не валидатора ArchMap)")
    assert _есть(w, "НЕ выдумывай замену")
    assert _есть(w, "убрать канал, а не добавить рядом похожий")
    # Маршрутизатор, а не судья: непогашенное — дословно пользователю.
    assert _есть(w, "маршрутизатор, а не судья")
    assert _есть(w, "попадает в финальный ответ ДОСЛОВНО")
    assert _есть(w, "ДОСЛОВНО и ЦЕЛИКОМ")  # последний отчёт в финале


@pytest.mark.parametrize("flow", ПОТОКИ)
def test_обёртка_учит_чинить_замечания_валидатора(flow):
    """⚠ Находка полевой приёмки Ф5 («порочный круг»): субагент отчитывался
    «Исправление: добавлена связь…», не тронув файл, — пользователь трижды нёс в
    ArchMap байт-в-байт тот же документ и трижды получал то же замечание. Раздел
    обязан нести три вещи: чинит СУБАГЕНТ (не оркестратор текстом), правка ТОЧЕЧНАЯ
    (документ целиком не перепечатывается) и ПРОВЕРЕННАЯ оркестратором в файле."""
    w = build_orchestrated_prompt(БЛОК_А, БЛОК_Б, flow)

    assert "## Если пользователь пришлёт замечания валидатора ArchMap" in w
    # Замечания узнаются по вступлению кнопки «Скопировать замечания для агента».
    assert _есть(w, "Валидатор импорта ArchMap")
    assert _есть(w, "Валидатор дозаливки")
    # Чинит субагент, а не ответ в чат.
    assert _есть(w, "НЕ отвечай на замечания текстом и НЕ чини сам")
    assert _есть(w, "Запусти субагента-строителя")
    # Точечно: перепечатка документа целиком — отдельный класс потерь.
    assert _есть(w, "внеси ТОЧЕЧНЫЕ правки по замечаниям")
    assert _есть(w, "документ целиком НЕ перепечатывай")
    # Главная строка фикса: отчёт только после проверки файла глазами.
    assert _есть(w, "САМ прочитай изменённые места файла и убедись, что правка в файле ЕСТЬ")
    assert _есть(w, "Отчитываться об исправлении, не увидев его в файле, ЗАПРЕЩЕНО")
    # Пользователю в ответе — адрес правки, а не «готово».
    assert _есть(w, "назови путь к файлу и что именно в нём изменилось")


