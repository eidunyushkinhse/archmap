# ⚠ Литерал порога V1 — копия текста из docs/qa-skeptic-threshold.md. Расхождение с
# app/skeptic_prompt.py означает, что порог кто-то переписал редактурой, а не
# экспериментом (и тест обязан это поймать).
ПОРОГ_V1 = (
    "Сомнение записывается ТОЛЬКО при конкретном доказательстве: процитированная "
    "строка кода, доказывающая обратное, или результат поиска, в котором имя не "
    "находится. Умозаключения без доказательства («обычно делают иначе», «вероятно, "
    "это не так») сомнением не являются — не записывай их вовсе. Не уверен — молчи: "
    "пропущенное сомнение дешевле ложного."
)


def _между(текст: str, начало: str, конец: str) -> str:
    """Срез между маркерами — ровно то, что агенту велено положить в файл."""
    return текст.split(начало)[1].split(конец)[0]


def _есть(промпт: str, кусок: str) -> bool:
    """Подстрока с точностью до переносов строк: тексты промптов переносятся по ширине
    исходника и меняют разбивку от любой подстановки. Слова и их порядок тест держит,
    место переноса — нет."""
    return " ".join(кусок.split()) in " ".join(промпт.split())


