def test_разведка_пути_файлов_согласованы_с_заданиями_субагентов():
    """⚠ Тот же класс, что ловушка №4 импорта: рассинхрон пути = сломанная петля. Здесь
    он опаснее — путей три. Тест вынимает ВСЕ .yaml-пути из шагов обёртки и требует,
    чтобы это были ровно два служебных файла прогонов и один итоговый в корне, а тела
    заданий писали КАЖДОЕ в свой файл."""
    петля = build_recon_orchestrated_prompt(
        lambda путь: build_recon_prompt("Ярмарка / orders", result_path=путь),
        build_skeptic_prompt("recon", orchestrated=True),
    )
    шаги = петля.split(BLOCK_A_START)[0]  # блоки-задания вшиты дословно, их не сверяем

    assert set(re.findall(r"`([^`\s]*\.yaml)`", шаги)) == {RECON_FILE, RECON_RUN_1, RECON_RUN_2}
    # Задание каждого разведчика называет СВОЙ файл и не называет чужой и не корневой:
    # иначе два прогона уедут в один файл и объединять будет нечего.
    for маркеры, свой, чужой in (
        ((BLOCK_A_START, BLOCK_A_END), RECON_RUN_1, RECON_RUN_2),
        ((BLOCK_B_START, BLOCK_B_END), RECON_RUN_2, RECON_RUN_1),
    ):
        тело = _между(петля, *маркеры)
        assert свой in тело
        assert чужой not in тело
        assert RECON_FILE not in тело
    # Скептик проверяет ИТОГ объединения, а не файл прогона.
    скептик = _между(петля, BLOCK_C_START, BLOCK_C_END)
    assert RECON_FILE in скептик
    assert RECON_RUN_1 not in скептик and RECON_RUN_2 not in скептик


