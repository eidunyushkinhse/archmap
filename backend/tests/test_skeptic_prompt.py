def test_orchestrated_меняет_только_адресные_части():
    """Режимы отличаются адресами (где пакет, куда отчёт) — не ролью, не чек-листом и
    не порогом: иначе standalone и петля разъедутся по качеству аудита."""
    один = build_skeptic_prompt("import", system_name="Ярмарка", orchestrated=False)
    в_петле = build_skeptic_prompt("import", system_name="Ярмарка", orchestrated=True)

    # Адресные части.
    assert _есть(один, "`architecture.yaml` в корне репозитория")
    assert "archmap-orch/architecture.yaml" in в_петле
    assert _есть(один, "`archmap-skeptic-report.md` в корне репозитория")
    assert "archmap-orch/skeptic-report-<N>.md" in в_петле
    assert _есть(в_петле, "следующий свободный номер (1, 2, …)")
    # Standalone дублирует отчёт в ответ — пользователь передаёт его руками.
    assert _есть(один, "продублируй его текст в ответ целиком")
    assert not _есть(в_петле, "продублируй его текст в ответ целиком")

    # Общая часть — байт-в-байт одна и та же.
    def тело(p: str) -> str:
        return p.split("## Что проверить")[1].split("## Формат отчёта")[0]

    assert тело(один) == тело(в_петле)


def test_standalone_несёт_инструкцию_передачи_строителю():
    """⚠ Ловушка №4 плана: замечания АУДИТА чинятся иначе, чем замечания ВАЛИДАТОРА
    («дополняй, не удаляй»), и источник обязан быть назван — иначе правила смешаются
    в одной сессии строителя."""
    p = build_skeptic_prompt("docs", orchestrated=False)
    assert _есть(p, "передайте отчёт агенту, который собирал пакет")
    assert _есть(p, "Это замечания АУДИТА по коду (не валидатора ArchMap)")
    assert _есть(p, "удали и НЕ выдумывай замену")
    # В петле отчёт забирает оркестратор — инструкции пользователю здесь не место.
    assert not _есть(build_skeptic_prompt("docs", orchestrated=True), "передайте отчёт агенту")


