@pytest.mark.parametrize("flow", ПОТОКИ)
def test_правила_и_формат_отчёта(flow):
    p = build_skeptic_prompt(flow)
    # Аудитор не чинит: пакет правит другой агент, иначе сессия «согласится с собой».
    assert _есть(p, "НИЧЕГО не исправляй: ни файлы пакета, ни другие файлы репозитория")
    assert _есть(p, "Твой выход — только отчёт")
    assert _есть(p, "Не советуй, как чинить")
    assert _есть(p, "Подтверждённое в отчёт НЕ включай")
    assert _есть(p, "Не выдумывай сомнений ради объёма")
