// Автозаполнение браузера в формах продукта (всё, кроме входа и смены пароля).
//
// Находка приёмки тура демо (2026-10-05): после создания связи Chrome предложил
// «Сохранить данные о транспортном средстве?» — его классификатор принял поля
// «Описание»/«Технология» за автомобильные. Голого autocomplete="off" для этого мало:
// по исходникам Chromium (autofill_ai_import_util.cc, determine_attribute_types.cc)
// предложение сохранить сущность (машина, паспорт…) строится по ПРЕДСКАЗАННЫМ типам
// полей и атрибут autocomplete не смотрит. Поэтому обезвреживаем сами сигналы:
//   - name. У наших полей не было ни name, ни id, а сигнатура поля и формы в
//     Chrome — хэш имён полей и хоста (без порта). Безымянные поля «формы без
//     <form>» делили сигнатуру со всеми такими же безымянными формами того же хоста
//     (на localhost — чужих сайтов разработчиков), и краудсорсинговые предсказания
//     сервера Autofill (в том числе «марка/модель машины») могли приезжать к нам.
//     Уникальное нейтральное имя `archmap-…` делает сигнатуру своей и не даёт
//     классификатору знакомых слов;
//   - autocomplete="off". Гасит историю ввода Chrome (с именем поле иначе стало бы
//     ей доступно) и автозаполнение в Firefox/Safari, которые атрибут слушают.
// Логин и смена пароля НЕ используют эту функцию: там автозаполнение нужно
// (username/current-password/new-password).

export interface NoAutofillProps {
  name: string;
  autoComplete: "off";
}

/** Атрибуты текстового поля, отключающие автозаполнение браузера. key — короткий
 *  нейтральный ключ поля (уникален в пределах окна/формы). */
export function noAutofill(key: string): NoAutofillProps {
  return { name: `archmap-${key}`, autoComplete: "off" };
}
