// Числовые константы и идентичность графа уровня. Без внутренних зависимостей —
// фундамент, на который опираются остальные модули graph/.
import { Position } from "@xyflow/react";
import type { NodeShape } from "../../types";

export const NODE_W = 190;
export const NODE_H = 100; // явная высота — нужна для правильного позиционирования хэндлов
// Узел-человек выше остальных: ему нужна крупная голова сверху, чтобы не выглядеть
// комично (маленькая голова на широких «плечах»).
export const PERSON_H = 130;

// Высота узла по форме. Человек — выше, остальные — стандартной высоты.
export function shapeHeight(shape: NodeShape): number {
  return shape === "person" ? PERSON_H : NODE_H;
}

// «Магнитный» диапазон выравнивания при драге: если центр узла подтянут ближе
// этого (в координатах графа) к центру соседа по X или Y — координата приравнивается
// так, чтобы центры совпали. По духу близко к reconnectRadius у хэндлов.
export const SNAP_THRESHOLD = 10;

// Примагничивание плеча стрелки к ровному положению относительно хэндла — порог в
// ЭКРАННЫХ пикселях (делится на зум при использовании, чтобы липкость не зависела от
// масштаба). См. snapDragCursor в edgePath.ts.
export const EDGE_SNAP_PX = 8;

// Диапазон авто-подбора шрифта чипа «роль: технология» (px)
export const MAX_TAG_FONT = 11;
export const MIN_TAG_FONT = 7;

// Авто-фит имени узла: имя переносится не более чем на MAX_NAME_LINES строки и
// уменьшает шрифт от MAX до MIN, пока целиком влезает в этот лимит строк — чтобы
// длинное имя не выдавливало чип «роль: технология» за нижний край узла. Если даже
// на минимальном шрифте не лезет — обрезается многоточием (line-clamp).
