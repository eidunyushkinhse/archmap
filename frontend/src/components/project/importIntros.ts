// Вступления к замечаниям, которые пользователь уносит своему ИИ-агенту.
//
// Разные по случаям, и это НЕ косметика: полевой QA (docs/qa-zabbix-7.md, раунд 2)
// показал, что на «исправь» слабая модель отвечает ампутацией — вырезает объекты
// вместо поиска связей (31→27, затем 30→14 узлов). Ошибки разбора чинятся
// правкой; предупреждения зелёной сводки — ДОПОЛНЕНИЕМ. Мульти-варианты
// добавляют к тому же уроку контекст «твой файл — один из многих»: иначе агент
// правит чужие куски вслепую или переписывает всю систему.
//
// Отдельный модуль от панели: этими же словами копируются замечания свёртки
// «Что исправит только новый прогон агента» — в обоих окнах ввоза (§6 ТЗ).
export const INTRO_ONE_OK =
  "Валидатор импорта ArchMap принял YAML, но оставил предупреждения. Устрани их, " +
  "ДОПОЛНЯЯ схему — находи и дописывай недостающие связи, а НЕ удаляй объекты: " +
  "удаление хуже недостающей связи. Выведи весь YAML-документ целиком заново:";
export const INTRO_ONE_BAD =
  "Валидатор импорта ArchMap нашёл замечания к YAML. Исправь их и выведи весь " +
  "YAML-документ целиком заново:";
export const INTRO_MANY_OK =
  "Валидатор импорта ArchMap принял ваш YAML — один из нескольких файлов системы, — " +
  "но оставил предупреждения. Устрани их, ДОПОЛНЯЯ схему — находи и дописывай " +
  "недостающие связи, а НЕ удаляй объекты: удаление хуже недостающей связи. " +
  "Выведи весь СВОЙ YAML-документ целиком заново:";
export const INTRO_MANY_BAD =
  "Валидатор импорта ArchMap нашёл замечания к вашему YAML-файлу — одному из " +
  "нескольких файлов системы. Исправь их и выведи весь СВОЙ YAML-документ целиком " +
  "заново:";

/** Вступление по случаю: сколько входов и приняты ли они. */
export const introFor = (multi: boolean, ok: boolean): string =>
  multi ? (ok ? INTRO_MANY_OK : INTRO_MANY_BAD) : (ok ? INTRO_ONE_OK : INTRO_ONE_BAD);
