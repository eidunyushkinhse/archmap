import type { NodeDoc, NodeDocMeta } from "../../types";

// Мета дока (без content) — для стейта узла: имя/вид/операция/версия/признак
// «описана». Версия входит в сигнатуру меты поллинга (V53): правка КОНТЕНТА доков
// видна странице как изменение данных даже без смены имени/вида.
//
// described сервер считает выражением в БД (тело непустое после trim), но здесь
// мета собирается РУКАМИ из ответа правки — и признак обязан пересчитаться тут же:
// иначе описанная в оверлее заглушка осталась бы в списке «не описана», а счётчик
// «описано N из M» откатился бы назад до перезагрузки страницы.
export function docToMeta(d: NodeDoc): NodeDocMeta {
  return {
    id: d.id,
    name: d.name,
    kind: d.kind,
    operation: d.operation,
    version: d.version,
    described: d.content.trim() !== "",
  };
}
